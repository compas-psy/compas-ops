#!/usr/bin/env bash
# HELM · какой именно страж отклоняет ответ и как часто.
#
# ЗАЧЕМ. Данные (прогон 546) показали: 29 отказов из 30 — это «нашёл,
# но не подтвердил», то есть ответ БЫЛ и его отклонил страж. Какой
# именно — в базе не записано: `parse_response` пишет причину
# предупреждением в журнал и возвращает наружу один и тот же
# `_REJECTED`. Значит ответ на вопрос «что чинить» лежит в журнале
# контейнера, а не в таблице.
#
# ЧТО СЧИТАЕТСЯ. Пять формулировок, которые пишет synthesis.py:
#   • чисел нет в источниках      (ungrounded_numbers)
#   • названий нет в источниках   (ungrounded_words)
#   • значения при чужом объекте  (unbound_claims)
#   • определения нет в источниках (undefined_subjects)
#   • маркер цитирования не разобран
# Плюс отдельно — «локальный синтез недоступен, откат на composer»:
# это причина режима Z1, которого в данных пятая часть.
#
# ПРИВАТНОСТЬ. В хвосте предупреждения стоит СПИСОК того, что страж
# счёл невподтверждённым, — а это куски ответа о здоровье владельца.
# Он не печатается: список заменяется числом элементов. Для решения
# «какой страж чинить» хватает категории и количества.
set -uo pipefail
cd /opt/helm/compose || exit 1

HOURS="${1:-168}"

echo "############ ВЫКАЧЕНО ############"
echo "SHA: $(sudo cat /opt/helm/DEPLOYED_SHA 2>/dev/null || echo unknown)"
echo "  окно журнала: последние ${HOURS} ч"
echo

LOG=$(mktemp)
trap 'rm -f "$LOG"' EXIT
sudo docker compose logs --since "${HOURS}h" --no-color helm-core 2>&1 \
  | grep -E "синтез отброшен|локальный синтез недоступен" > "$LOG" || true

TOTAL=$(wc -l < "$LOG")
echo "############ СКОЛЬКО ############"
echo "  строк про отказ синтеза: $TOTAL"
if [ "$TOTAL" -eq 0 ]; then
  echo "  журнал за это окно пуст — контейнер мог перезапускаться, окно можно расширить аргументом"
  exit 0
fi
echo

echo "############ ПО ПРИЧИНАМ ############"
for pattern in "чисел нет в источниках" "названий нет в источниках" \
               "значения при чужом объекте" "определения нет в источниках" \
               "маркер цитирования не разобран" "локальный синтез недоступен"; do
  count=$(grep -c "$pattern" "$LOG" || true)
  printf '  %-34s %s\n' "$pattern:" "$count"
done
echo

echo "############ ПО ДНЯМ ############"
awk '{print $1}' "$LOG" | cut -c1-10 | sort | uniq -c | tail -14
echo

echo "############ ПРИМЕРЫ БЕЗ СОДЕРЖИМОГО ############"
echo "(список отклонённого заменён его длиной: сами значения — данные владельца)"
grep -E "синтез отброшен" "$LOG" | tail -8 | sed -E "s/\[[^]]*\]/[список скрыт]/g" \
  | sed -E "s/^([^ ]+ [^ ]+).*(синтез отброшен[^:]*(: |$))/\1 \2/"
