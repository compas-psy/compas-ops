#!/usr/bin/env bash
# HELM · освободить диск. Обслуживание: удаляется только то, что
# восстанавливается само.
#
# ЭТО РАЗОВАЯ УБОРКА, а не постоянный порядок. Постоянный —
# `helm-cleanup.timer` (§25.6, каждый час, `guardian/cleanup.sh`).
# Этот скрипт понадобился потому, что таймера на сервере не было
# вовсе и 41 ГБ уже накопился; он остаётся на случай, когда нужно
# освободить диск немедленно, не дожидаясь часа.
#
# ИЗМЕРЕНО (прогон 450): диск 79 из 99 ГБ, 84%. Причина одна —
# кэш сборки docker: 238 записей, 41.29 ГБ, из них активных НОЛЬ,
# reclaimable 100%. Накопился от `docker compose build helm-core
# helm-knowledge-worker` на каждом выкате, а выкатов только за
# 07.09.2026 больше пятидесяти.
#
# ЧТО УДАЛЯЕТСЯ И ПОЧЕМУ ЭТО БЕЗОПАСНО:
#
#   кэш сборки — промежуточные слои прошлых сборок. Данных в нём нет,
#   образы на нём не стоят (ACTIVE 0). Единственная цена — следующая
#   сборка пойдёт без кэша, то есть дольше. Сам кэш соберётся заново;
#
#   журнал systemd ужимается до 200 МБ, не удаляется;
#
#   apt-кэш — скачанные .deb, которые уже установлены.
#
# ЧТО НЕ ТРОГАЕТСЯ НАМЕРЕННО:
#
#   образы — все девять под контейнерами (проверено прогоном 450);
#   тома — 760 МБ безымянных с LINKS 0 выглядят мусором, но том может
#   держать данные, и разбирать их надо отдельно и глядя в каждый;
#   `helm_ollama_models` (10.69 ГБ) — рабочие модели, не мусор;
#   точки возврата (173 МБ, три штуки) — страховка выката.
set -uo pipefail
cd /opt/helm/compose || exit 1

echo "выкачено: $(sudo cat /opt/helm/DEPLOYED_SHA 2>/dev/null || echo unknown)"

echo "############ БЫЛО ############"
df -h / | tail -1
sudo docker system df

echo
echo "############ 1. КЭШ СБОРКИ ############"
sudo docker builder prune -af 2>&1 | tail -3

echo
echo "############ 2. ЖУРНАЛ SYSTEMD ############"
sudo journalctl --vacuum-size=200M 2>&1 | tail -2

echo
echo "############ 3. APT-КЭШ ############"
sudo apt-get clean 2>&1 | tail -1
echo "  /var/cache/apt: $(sudo du -sh /var/cache/apt 2>/dev/null | cut -f1)"

echo
echo "############ СТАЛО ############"
df -h / | tail -1
sudo docker system df

echo
echo "############ ПРОВЕРКА: СЛУЖБЫ ЖИВЫ ############"
sudo docker compose ps --format 'table {{.Service}}\t{{.Status}}' 2>&1 | head -12
