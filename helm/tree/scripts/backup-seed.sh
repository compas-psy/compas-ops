#!/bin/bash
# Первичное заполнение offsite-репозитория маленькими порциями.
#
# Зачем. Четыре прогона обычного `backup.sh` подряд (02.09.2026) упали на
# одном и том же: Яндекс отвечает 500/EOF на отдельные блоки, когда за
# раз выгружается шестьдесят мегабайт. Ни таймауты, ни ограничение
# темпа, ни размер пачки этого не изменили. При этом инкремент почти без
# новых данных проходит за двадцать секунд и проходил десятки раз.
#
# Отсюда приём, стандартный для первой заливки по ненадёжному каналу:
# не одна большая выгрузка, а несколько маленьких. Каждый успешный
# `restic backup` навсегда закрепляет свои блоки в репозитории, а данные
# в restic адресуются содержимым — поэтому следующая выгрузка не
# отправляет то, что уже лежит. Когда все порции прошли, обычный
# ежедневный бэкап становится тем самым инкрементом на двадцать секунд.
#
# Скрипт идемпотентен: повторный запуск пропускает то, что уже
# выгрузилось, и доделывает остаток. Падение порции — не отказ всего
# заполнения: помечаем и идём дальше, к ней вернётся следующий запуск.
set -uo pipefail

if [ "$(id -u)" -ne 0 ]; then exec sudo bash "$0" "$@"; fi

export RESTIC_REPOSITORY="rclone:yandex:helm-backup"
export RESTIC_PASSWORD_FILE="/etc/helm/secrets/restic_password"
export RCLONE_TIMEOUT=10m
export RCLONE_CONTIMEOUT=2m
export RCLONE_LOW_LEVEL_RETRIES=20

#: Бюджет по времени. Раннер убивает джобу на шестидесяти минутах, и
#: оборванный на полуслове прогон хуже честно недоделанного: во втором
#: случае видно, докуда дошли.
BUDGET_SECONDS=${BUDGET_SECONDS:-2400}
#: Порция. Меньше — больше шансов пройти, но и больше отдельных
#: снапшотов; десять файлов это единицы мегабайт.
BATCH=${BATCH:-10}

started=$(date +%s)
left() { echo $(( BUDGET_SECONDS - ( $(date +%s) - started ) )); }

ok=0; failed=0; skipped=0

seed() {
  local label="$1"; shift
  if [ "$(left)" -lt 120 ]; then
    skipped=$((skipped + 1))
    return
  fi
  echo "--- $label ($# файлов, осталось $(left) с) ---"
  if timeout "$(left)" restic backup --tag helm-seed --pack-size 4 "$@" 2>&1 \
      | tail -3; then
    ok=$((ok + 1))
  else
    echo "    порция не прошла — вернёмся к ней следующим запуском"
    failed=$((failed + 1))
  fi
}

echo "############ ЗАПОЛНЕНИЕ ПОРЦИЯМИ ############"
echo "бюджет: $BUDGET_SECONDS с, размер порции: $BATCH файлов"
echo

# Порядок важен: сначала приватное дерево. Оно и есть то, чего в
# репозитории нет, и ради чего всё это делается.
for root in /opt/helm-knowledge-private /opt/helm-knowledge; do
  [ -d "$root" ] || continue
  echo "===== $root ====="
  n=0
  batch=()
  while IFS= read -r f; do
    batch+=("$f")
    if [ "${#batch[@]}" -ge "$BATCH" ]; then
      n=$((n + 1))
      seed "$root порция $n" "${batch[@]}"
      batch=()
    fi
  done < <(find "$root" -type f \
             -not -path '*/skills/*' -not -path '*/derived/*' | sort)
  if [ "${#batch[@]}" -gt 0 ]; then
    n=$((n + 1))
    seed "$root порция $n (хвост)" "${batch[@]}"
  fi
done

echo
echo "############ ИТОГ ############"
echo "порций прошло: $ok, не прошло: $failed, не начато по бюджету: $skipped"

if [ "$failed" = "0" ] && [ "$skipped" = "0" ]; then
  echo
  echo "Всё выгружено. Теперь обычный backup.sh должен пройти инкрементом:"
  echo "данные уже в репозитории, отправлять почти нечего."
else
  echo
  echo "Осталась работа. Запустите этот же скрипт ещё раз — он продолжит"
  echo "с того места, где остановился: то, что уже выгружено, повторно"
  echo "не отправляется."
fi
