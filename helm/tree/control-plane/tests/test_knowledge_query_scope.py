"""О чьих данных вопрос. От этого зависит право потратить деньги.

Распоряжение владельца 06.09.2026: «Отсутствие находок не является моим
разрешением оплатить ответ». Запретить оплату при пустом поиске нельзя
безусловно — тогда без ответа остались бы «переведи текст» и «что такое
ферритин», к личным данным не относящиеся. Разграничение и есть предмет
этих проверок.

ЦЕНА ОШИБКИ НЕСИММЕТРИЧНА. Ложно «личный» — не заплатили за ответ,
который платная модель могла дать. Ложно «общий» — заплатили за выдумку
о здоровье владельца. Второе хуже, поэтому проверок на «личный» больше
и они шире.
"""

from __future__ import annotations

import pytest

from helm_core.knowledge.query_scope import is_personal_data_question


@pytest.mark.parametrize("query", [
    "что там прописал врач?",
    "каких врачей я посещал?",
    "какое у меня было давление?",
    "мои анализы за март",
    "где я работал в 2019 году?",
    "в моих записях есть что-то про ферритин?",
    "мне назначили что-то от давления?",
    "меня наблюдал кардиолог?",
    "я принимаю что-нибудь от щитовидки?",
    "по моим документам когда была операция",
    "из своих заметок найди про переезд",
])
def test_question_about_own_data_is_personal(query):
    assert is_personal_data_question(query) is True, query


@pytest.mark.parametrize("query", [
    "переведи мне этот текст на английский",
    "что такое ферритин?",
    "объясни, как работает индексация",
    "сколько будет 2+2",
    "напиши письмо в поддержку",
    "что там в новостях?",
    "какая погода завтра",
    "перескажи мне статью по ссылке",
])
def test_general_question_is_not_personal(query):
    assert is_personal_data_question(query) is False, query


def test_dative_of_benefit_is_not_ownership():
    """«Переведи МНЕ текст» — дательный выгоды. Если считать его
    признаком владения данными, запрет оплаты снесёт половину обычной
    работы бота вместе с выдумками."""
    assert is_personal_data_question("переведи мне текст") is False
    assert is_personal_data_question("расскажи мне про витамин D") is False
    # А вот это уже про данные владельца, тем же словом.
    assert is_personal_data_question("что мне назначили в марте") is True


def test_deictic_needs_a_record_word():
    """«Что там» указывает на обсуждавшийся документ только вместе со
    словом о записи. Иначе под правило попадёт «что там в новостях»."""
    assert is_personal_data_question("что там в заключении?") is True
    assert is_personal_data_question("что там на улице?") is False
