"""Персональный стиль для Z2-рефраза (§14.12, §14.14 P8.6.6).

Источник — скил `my-writing-style` (личный аккаунт владельца, собран
20.08.2026 по его собственным опубликованным постам). Скил живёт в
Claude-аккаунте владельца, не в этом репозитории — боевой сервер к нему
доступа не имеет вовсе, поэтому здесь не "чтение скила", а его
СНИМОК: то, что из профиля переносится на короткий Z2-рефраз, взято и
адаптировано вручную, версионируется как обычный код.

Сознательно НЕ перенесено из скила (осмысленное сужение, не пропуск):
скил написан под ПУБЛИКАЦИИ (посты Telegram/VC.ru/Дзен, 700-3200
знаков) — длина, открывашка-сцена, крючок на следующий пост, разбор
конкретного примера ("шакшука") не имеют отношения к Z2: та отвечает на
один конкретный вопрос себе самому одной-двумя фразами, не пишет пост.
Перенесены только правила ТОНА и РЕГИСТРА, применимые к любой длине
текста — разговорность, живые обороты, список ИИ-штампов, обращение.

`KnowledgeUser.style_profile_version` (схема существует с v3.8, до
этого момента не использовалась) — версия этого файла, применённая к
конкретному пользователю; при следующем существенном изменении профиля
номер версии увеличивается, чтобы можно было отличить ответ "до" и
"после" правки стиля постфактум.
"""

from __future__ import annotations

#: Увеличивать при любом смысловом изменении STYLE_PROMPT ниже —
#: KnowledgeUser.style_profile_version сверяется с этим числом.
OWNER_STYLE_VERSION = 1

#: Системный промпт для Ollama-рефраза (§14.12: "модель видит только
#: evidence pack" — этот текст задаёт ТОЛЬКО тон изложения, не источник
#: фактов; сама модель не имеет доступа ни к чему, кроме evidence и
#: вопроса, см. rephrase.py).
OWNER_STYLE_PROMPT = """\
Перефразируй факт естественным разговорным тоном — так, как сам \
человек рассказал бы это в двух словах, а не как справка.

Держись этих привычек:
- Разговорно, не по-канцелярски. "Получается, что" вместо "таким \
образом"; "если честно" — где уместно.
- Восклицательный знак — только если содержание того стоит, не по \
умолчанию.
- Обращение на "вы".
- Если в тексте есть термин — не оставляй его висеть, коротко поясни \
своими словами тут же.
- Короткое предложение можно оставить отдельной строкой, если это \
даёт эффект, но не через раз — это редкий приём, не тик.

Никогда не используй: "давайте разберёмся", "важно понимать", \
"ключевой момент", "в этом и суть", "стоит отметить", "в современном \
мире", "сегодня всё больше людей", капс для выделения, тройки \
одинаковых по длине пунктов, обещание результата.

Не добавляй ничего, чего нет в тексте ниже. Не сокращай факт до \
неузнаваемости. Если факт короткий — рефраз тоже должен быть коротким, \
не растягивай его до абзаца."""


def style_prompt_for_version(version: int) -> str | None:
    """`None`, если версия не распознана — вызывающая сторона (rephrase.py)
    обязана в этом случае звать модель БЕЗ стилевого промпта, не падать:
    рефраз без стиля — тот же корректный деградированный путь, что и
    "модель недоступна вовсе" (см. KNOWLEDGE_MODELS.md)."""
    if version == OWNER_STYLE_VERSION:
        return OWNER_STYLE_PROMPT
    return None
