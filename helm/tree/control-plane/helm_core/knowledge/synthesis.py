#: Слово, по которому фрагмент можно узнать в ответе: четыре и более
#: символов, включая точки и слэши (адреса, коды услуг, номера).
_TOKEN_RE = re.compile(r"[0-9a-zа-яё][0-9a-zа-яё._/\-]{3,}", re.IGNORECASE)

#: ЧИСЛА проверяются отдельно и по другому правилу. Найдено на живом
#: ответе владельцу 07.09.2026: на «какой у меня холестерин был в
#: последний раз» пришло «8.1 ммоль/л», а в корпусе этого значения нет
#: вовсе — ближайшее «Холестерин 6.2» от 07.10.2023. Проверка
#: заземления его пропустила, потому что «8.1» короче четырёх символов
#: и словом не считалась: самая ответственная часть ответа —
#: измеренное значение — не проверялась ничем.
_NUMBER_RE = re.compile(r"\d+(?:[.,]\d+)?(?:\s*/\s*\d+(?:[.,]\d+)?)?")

#: Маркер вырезается ГДЕ УГОДНО, не только отдельной строкой. Живой
#: ответ владельцу 07.09.2026: «Регистрация должна быть проведена до
#: 16:48 23.08.2026. ФРАГМЕНТЫ: 2» — модель дописала маркер в конец
#: предложения, якорь `^…$` его не увидел, и служебная разметка ушла в
#: мессенджер. `[ \t]`, а не `\s`: перевод строки не должен утягивать в
#: маркер цифры следующего абзаца.
#: Окончание слова и разделитель номеров не фиксированы: при одном
#: источнике модель пишет «ФРАГМЕНТ: 1», а номера перечисляет и через
#: запятую, и союзом. Разведка 10.09.2026 по журналу: «маркер не
#: разобран» — 4 отказа из 13 за неделю, и терялись на этом ВЕРНЫЕ
#: ответы.
_CITATION_RE = re.compile(r"[ \t]*ФРАГМЕНТ\w*[ \t]*:[ \t]*([0-9](?:[0-9,]|[ \t]|и)*)",
                          re.IGNORECASE)
#: Остаток маркера после вырезания — признак, что формат разобран не
#: до конца. Показывать такой ответ нельзя: раз одну служебную строку
#: мы не узнали, неизвестно, что ещё в тексте не ответ.
#:
#: Ищется именно МАРКЕР — слово с двоеточием, — а не слово «фрагмент».
#: Прежнее правило отклоняло ответ за любое его употребление, хотя
#: модель, которую промпт просит отвечать ПО ФРАГМЕНТАМ, законно пишет
#: «во фрагменте указано…». Верный ответ с разобранным маркером
#: выбрасывался целиком (разведка 10.09.2026).
_CITATION_LEFTOVER_RE = re.compile(r"ФРАГМЕНТ\w*[ \t]*:", re.IGNORECASE)
_NO_ANSWER_RE = re.compile(r"НЕТ\s+ОТВЕТА", re.IGNORECASE)


def _tokens(text: str) -> set[str]:
    return {match.group(0).lower().strip("._/-") for match in _TOKEN_RE.finditer(text)}


def _numbers(text: str) -> set[str]:
    """Числа текста в сравнимом виде: запятая → точка, пробелы убраны,
    хвостовые нули отброшены («8,10» и «8.1» — одно число)."""
    found = set()
    for match in _NUMBER_RE.finditer(text):
        raw = match.group(0).replace(",", ".").replace(" ", "")
        parts = []
        for part in raw.split("/"):
            if "." in part:
                part = part.rstrip("0").rstrip(".")
            parts.append(part or "0")
        found.add("/".join(parts))
    return found


#: Год как год, а не как любое четырёхзначное число. Двузначный —
#: только внутри даты: «25.08.26» → 2026, но «26» само по себе годом не
#: считается, иначе годом станет любой номер строки бланка.
_YEAR_RE = re.compile(r"(?<!\d)(?:19|20)\d{2}(?!\d)")
_SHORT_YEAR_RE = re.compile(r"(?<!\d)\d{1,2}[./-]\d{1,2}[./-](\d{2})(?!\d)")


def _supported_years(fragments: list[str]) -> set[str]:
    """Годы, которые источники действительно называют."""
    years: set[str] = set()
    for fragment in fragments:
        years |= set(_YEAR_RE.findall(fragment))
        years |= {f"20{short}" for short in _SHORT_YEAR_RE.findall(fragment)}
    return years


def ungrounded_numbers(answer: str, fragments: list[str]) -> set[str]:
    """Числа ответа, которых нет ни в одном показанном фрагменте.

    Непустой результат означает, что модель ЧТО-ТО ПРИДУМАЛА: значение
    анализа, дату, дозировку. Такой ответ показывать нельзя — именно
    из-за него владелец 07.09.2026 получил несуществующий уровень
    холестерина с честно названным источником, где этого значения нет.

    Год прощается ТОЛЬКО тот, который источник действительно называет:
    ответ вправе сказать «в 2026 году», когда во фрагменте стоит
    «25.08.26». Прежнее правило прощало любое четырёхзначное число, и
    через эту дыру проходили дозировка «1000 мг», значение «1250» и
    цена — всё, что случайно оказалось в четыре знака. Год — это
    исключение про даты, а не про длину числа.
    """
    known = set()
    for fragment in fragments:
        known |= _numbers(fragment)
    supported = _supported_years(fragments)
    return {value for value in _numbers(answer) - known
            if not (value.isdigit() and len(value) == 4 and value in supported)}


#: Слово ответа, которое обязано быть в источнике: латиница в русском
#: ответе или заглавная буква НЕ в начале предложения. И то, и другое —
#: признак имени собственного, названия, термина, то есть содержания, а
#: не связки. Найдено на живом ответе 07.09.2026: во фрагменте владельца
#: стоял «ибопрофен», в ответе — «ibuprofene». Проверка чисел это
#: пропускала: буквы никто не сверял.
#:
#: Чего правило НЕ делает: не проверяет обычные слова («находятся»,
#: «составляет»). Требовать их в источнике значило бы запретить модели
#: связывать фрагменты своими словами — а ради этого синтез и заводился.
#: Ограничение названное, не закрытое.
_LATIN_RE = re.compile(r"[a-z]", re.IGNORECASE)
_WORD_RE = re.compile(r"[^\W\d_][\w\-]*", re.UNICODE)
#: Пять символов — общий корень словоформы: «зарядку»/«зарядка»,
#: «Аэрофлот»/«Аэрофлоте». Сверять целиком нельзя (падежи), сверять по
#: трём — пропустить половину выдумок.
_STEM_LEN = 5
_SENTENCE_END = ".!?:;\n"


#: Корни ИСТОЧНИКА берутся по отдельным словам, а не по `_TOKEN_RE`:
#: тот склеивает адрес «www.b17.ru/eliah» в один токен, и «eliah» из
#: ответа считался бы выдумкой, хотя стоит прямо во фрагменте.
_ANY_WORD_RE = re.compile(r"[0-9a-zа-яё]+", re.IGNORECASE)


def _stems(text: str) -> set[str]:
    return {word.lower()[:_STEM_LEN] for word in _ANY_WORD_RE.findall(text)}


def _name_matches(answer: str):
    """Слова ответа, похожие на название, вместе с их положением.

    Положение нужно `unbound_claims()`: чтобы спросить «чьё это
    значение», надо знать, что стоит В ОТВЕТЕ ПЕРЕД ним.
    """
    for match in _WORD_RE.finditer(answer):
        word = match.group(0)
        if len(word) < 4:
            continue
        head = answer[:match.start()].rstrip()
        at_sentence_start = not head or head[-1] in _SENTENCE_END
        if _LATIN_RE.search(word) or (word[:1].isupper() and not at_sentence_start):
            yield word, match.start()


def _name_like(answer: str) -> set[str]:
    """Слова ответа, похожие на название: латиница или заглавная не в
    начале предложения."""
    return {word.lower() for word, _ in _name_matches(answer)}


def ungrounded_words(answer: str, fragments: list[str]) -> set[str]:
    """Названия ответа, которых нет ни в одном показанном фрагменте."""
    known = set()
    for fragment in fragments:
        known |= _stems(fragment)
    return {word for word in _name_like(answer) if word[:_STEM_LEN] not in known}


#: Единицы измерения — закрытый список. Именно они отличают «значение
#: чего-то» от номера строки, кода услуги и года: проверка привязки
#: включается только там, где ответ утверждает измеренную величину.
_UNITS = (r"ммоль/л|мкмоль/л|мкг/л|мг/дл|мг/л|г/л|ме/л|ед/мл|"
          r"мм\s*рт\.?\s*ст\.?|уд/мин|ккал|"
          r"мг|мкг|кг|мл|см|мм|%")
#: Измерение: число с единицей. Публичное имя — им пользуется и
#: `operations.run_measurements()`: «значение» одинаково опознаётся и
#: когда проверяют ответ модели, и когда собирают ответ без модели.
MEASUREMENT_RE = re.compile(
    r"(\d+(?:[.,]\d+)?(?:\s*/\s*\d+(?:[.,]\d+)?)?)\s*(" + _UNITS + r")",
    re.IGNORECASE)


def _sentence_head(text: str, position: int) -> str:
    """Начало предложения до указанной позиции — там стоит название, к
    которому относится значение."""
    head = text[:position]
    cut = max(head.rfind(ch) for ch in _SENTENCE_END)
    return head[cut + 1:] if cut >= 0 else head


def _labelled_lines(fragment: str) -> list[str]:
    """Строки фрагмента, к каждой из которых приклеена строка-название
    над ней, если та сама чисел не содержит.

    Лабораторный бланк из PDF нередко разложен на две строки: название
    показателя отдельно, значение отдельно. Склейка только с БЕСЧИСЛОВОЙ
    строкой: строка, где числа есть, — это соседняя строка таблицы, и
    заимствовать у неё название значило бы разрешить ровно ту подмену,
    против которой вся проверка.
    """
    lines = fragment.splitlines()
    result = []
    for i, line in enumerate(lines):
        previous = lines[i - 1] if i else ""
        result.append(f"{previous}\n{line}" if previous and not any(
            ch.isdigit() for ch in previous) else line)
    return result


def _claim_values(answer: str):
    """Значения, которые ответ УТВЕРЖДАЕТ, и их положение в тексте.

    Два вида, и оба нуждаются в проверке принадлежности:

      измеренная величина — число с единицей («6.2 ммоль/л»). Опознаётся
      по единице: именно она отличает значение от номера строки, кода
      услуги и года;

      название — «Альфа», «Бета», латиница. Именно этот вид проверка
      07.09.2026 не покрывала вовсе, и на нём владелец показал дефект:
      «Поездка: страховщик Бета» и «Квартира: страховщик Альфа» давали
      подтверждённое «Страховщик поездки Альфа».
    """
    for match in MEASUREMENT_RE.finditer(answer):
        yield " ".join(match.group(0).split()), match.start(), _numbers(match.group(1)), set()
    for word, position in _name_matches(answer):
        yield word, position, set(), {word.lower()[:_STEM_LEN]}


def _distinctive(line_stems: set[str], rival: set[str]) -> set[str]:
    """Слова, которыми одна строка таблицы отличается от другой.

    ТОЛЬКО СЛОВА, НЕ ЦИФРЫ, И ЭТО НЕ ПРИДИРКА. Первая редакция правила
    брала любую разницу корней — а туда попадает само значение: «5.7»
    отличает строку ЛПНП от строки общего холестерина и стоит в ответе
    всегда, потому что ответ его и называет. Проверка получалась
    тождеством и не срабатывала ни разу.
    """
    return {stem for stem in line_stems - rival
            if len(stem) >= 4 and any(ch.isalpha() for ch in stem)}


def unbound_claims(answer: str, fragments: list[str]) -> set[str]:
    """Значения ответа, стоящие в источнике при ДРУГОМ объекте.

    Разница с `ungrounded_numbers()`/`ungrounded_words()` — вся суть.
    Те спрашивают «есть ли это во фрагментах», эта — «чьё оно».

    ДВА ИЗМЕРЕННЫХ ДЕФЕКТА, ОДИН МЕХАНИЗМ.

    07.09.2026, живой корпус: на «какой у меня был холестерин в
    последний раз» пришло «5.7 ммоль/л». Число во фрагментах было —
    строкой «(RBC) Эритроциты: 5.45 (4.3-5.7)», верхней границей нормы
    эритроцитов. Настоящее значение в корпусе одно: «Холестерин общий:
    6.2».

    07.09.2026, разбор владельца: «Поездка: страховщик Бета» и
    «Квартира: страховщик Альфа» давали подтверждённое «Страховщик
    поездки Альфа». Прежняя проверка требовала совпадения ОДНОГО слова
    строки с ответом — слова «страховщик» хватало, и строка про квартиру
    подтверждала утверждение про поездку.

    ПРАВИЛО. Строка источника подтверждает значение, только если несёт
    и само значение, и ВСЕ содержательные слова, стоящие в ответе перед
    ним, — а не одно из них. Проверяется строка, а не документ: в
    таблице соседняя строка это другой показатель.

    ПОЧЕМУ «ВСЕ», НО НЕ БУКВАЛЬНО ВСЕ. Требуются только те слова,
    которые в источниках вообще встречаются. Слово, которого во
    фрагментах нет нигде, — это либо пересказ («уровень холестерина» при
    источнике «Холестерин общий»), либо выдумка; выдумку ловит
    `ungrounded_words()`, а пересказ не должен отбраковывать верный
    ответ. Без этой оговорки правило отвергало бы и «Уровень
    холестерина 6.2 ммоль/л», где значение своё.

    СОСЕДНЯЯ СТРОКА ТОГО ЖЕ СЕМЕЙСТВА — ТРЕТИЙ ИЗМЕРЕННЫЙ ДЕФЕКТ
    (09.09.2026, прогон 494). После починки разбора таблиц в записи от
    23.08.2026 встали рядом четыре строки: «Холестерин общий: ↑ 8.4
    ммоль/л», «Холестерин-ЛПВП …», «Холестерин-ЛПНП (липопротеины
    низкой плотности): ↑ 5.7 ммоль/л», «Холестерин-неЛПВП …». На вопрос
    «какой у меня был холестерин» пришло «У вас холестерин 5.7 ммоль/л»
    — значение ЛПНП, поданное как холестерин, с честно названным
    источником. Правило выше это пропускало: слово «холестерин» есть и в
    той строке, требуемые слова совпали.

    ОТВЕТ ОБЯЗАН НАЗВАТЬ ОБЪЕКТ НЕ МЕНЕЕ ТОЧНО, ЧЕМ ИСТОЧНИК. Если во
    фрагментах есть другая строка с тем же требуемым словом, но ДРУГИМ
    измеренным значением, ответ обязан нести хоть одно слово, отличающее
    выбранную строку от соперницы. «Холестерин-ЛПНП 5.7» — несёт,
    «холестерин 5.7» — нет, и это отбраковка. Родня механизма —
    `operations.missing_comparison_side()`: там тоже сравниваются
    РАЗЛИЧАЮЩИЕ слова, а не все.

    Соперницей считается только строка с измерением (число плюс
    единица): номер услуги и год соперницами показателя не бывают.

    ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ. Не проверяет числа без единицы измерения —
    даты, счёт, коды: единицы нет, и отличить значение от номера нечем.
    Не понимает отрицания и уступки («не Альфа, а Бета» на строке с
    Альфой пройдёт). Не знает, что «холестерин» без уточнения означает
    общий: словаря показателей здесь нет и не будет. Когда соперница
    есть, а ответ не уточняет, исход — отказ, а не догадка.
    Ограничения названные, не закрытые.
    """
    lines = [line for fragment in fragments for line in _labelled_lines(fragment)]
    indexed = [(_stems(line), _numbers(line), bool(MEASUREMENT_RE.search(line)))
               for line in lines]
    known = set()
    for fragment in fragments:
        known |= _stems(fragment)
    answer_stems = _stems(answer)

    unbound = set()
    for value, position, numbers, stems in _claim_values(answer):
        required = {stem for stem in _stems(_sentence_head(answer, position))
                    if len(stem) >= 4 and stem in known and stem not in stems}
        if not required:
            continue
        carrying = [line_stems for line_stems, line_numbers, _measured in indexed
                    if (numbers and line_numbers & numbers)
                    or (stems and stems <= line_stems)]
        if not carrying:
            continue  # значения нет вовсе — это ловят проверки выше
        supporting = [line_stems for line_stems in carrying
                      if required <= line_stems]
        if not supporting:
            unbound.add(value)
            continue
        rivals = [line_stems for line_stems, line_numbers, measured in indexed
                  if measured and required <= line_stems
                  and line_numbers and not (line_numbers & numbers)]
        if rivals and not any(
                all(_distinctive(line_stems, rival) & answer_stems
                    for rival in rivals)
                for line_stems in supporting):
            unbound.add(value)
    return unbound


#: Определительный оборот. Тот же список, что у `operations.py` — но
#: применяется иначе: там он ОТБИРАЕТ фрагменты, здесь ПРОВЕРЯЕТ ответ.
#: «это» засчитывается только после тире: без тире оно стоит в каждом
#: втором предложении и определением не является.
_DEFINITION_MARK_RE = re.compile(
    r"[—–-]\s*это\b|\bназыва(?:ется|ются|ют)\b|\bименуется\b|"
    r"\bпредставляет\s+собой\b|\bопределяется\s+как\b|\bпонима(?:ется|ют)\b",
    re.IGNORECASE)


def _definiendum(text: str, position: int) -> set[str]:
    """Что именно определяют — слова перед оборотом в этом предложении."""
    return {stem for stem in _stems(_sentence_head(text, position)) if len(stem) >= 3}


def undefined_subjects(answer: str, fragments: list[str]) -> set[str]:
    """Объекты, которым ответ даёт определение, а источник — не даёт.

    ИЗМЕРЕННЫЙ ДЕФЕКТ (прогон 445, разбор владельца 07.09.2026). Книга
    говорит, что некоторое сочетание задач достигается В РАМКАХ ЭОТ.
    Ответ пришёл как «ЭОТ — это сочетание задач осознания и изменения»:
    описание работы внутри метода превратилось в определение самого
    метода. Слова все из источника, числа проверять нечего, источник
    назван честно — и утверждение всё равно чужое.

    ПРАВИЛО. Ответ, построенный как определение, засчитывается, только
    если в источнике есть строка, где определительный оборот стоит при
    ТОМ ЖЕ определяемом. Сравнивается левая часть: то, что источник
    ставит перед оборотом, обязано целиком входить в то, что ставит
    перед оборотом ответ.

    Отсюда и берётся разбор дефекта. Источник определяет «работу в
    рамках ЭОТ» — три слова; ответ определяет «ЭОТ» — одно. Слова
    «работа» и «рамки» ответ ОТБРОСИЛ, то есть расширил утверждение с
    частного случая на весь метод. Проверка это видит.

    ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ. Не знает синонимов: если источник определяет
    «ЭОТ», а ответ — «эмоционально-образную терапию», определение будет
    отклонено, хотя оно верно. Отклонение честно называется отклонением
    (`format_unverified`), а не превращается в «в документах ничего
    нет» — это разные исходы. Ограничение названное, не закрытое.

    Сравнение и пример этой проверкой не покрыты: форма для них
    отбирается в `operations.py` и сообщается владельцу отдельной
    строкой, но ОТКАЗА при её отсутствии пока нет.
    """
    source_definitions = []
    for fragment in fragments:
        for line in fragment.splitlines():
            for mark in _DEFINITION_MARK_RE.finditer(line):
                source_definitions.append(_definiendum(line, mark.start()))

    undefined = set()
    for mark in _DEFINITION_MARK_RE.finditer(answer):
        subject = _definiendum(answer, mark.start())
        if not subject:
            continue
        if not any(defined and defined <= subject for defined in source_definitions):
            undefined.add(" ".join(_sentence_head(answer, mark.start()).split()))
    return undefined


def _value_owners(answer: str, fragments: list[str]) -> set[int]:
    """Фрагменты, ЕДИНОЛИЧНО несущие какое-нибудь значение ответа.

    ИЗМЕРЕННЫЙ ДЕФЕКТ (разбор владельца 07.09.2026). Ответ берёт код
    проекта из первого источника и бюджет из второго, а ссылка остаётся
    только на первый. Причина в том, что вес считался на весь текст
    сразу: длинный код перевешивал короткое число, и второй источник не
    добирал половины лучшего веса.

    Доказательство обязано быть у КАЖДОГО утверждения, а не у ответа
    целиком. Фрагмент, оказавшийся единственным носителем значения,
    доказывает своё утверждение независимо от того, сколько весит
    соседний фрагмент со своим.

    Значением считается то же, что проверяет `unbound_claims()`, —
    величина, название, — плюс голое число. Случайная словоформа
    («ссылку») ни тем, ни другим не является и постороннего фрагмента
    сюда не втащит: ровно эта беда была прогоном 388, и порог веса
    заведён против неё.
    """
    owners: set[int] = set()

    def sole(holders: list[int]) -> None:
        if len(holders) == 1:
            owners.add(holders[0])

    for _value, _position, numbers, stems in _claim_values(answer):
        sole([i for i, fragment in enumerate(fragments, start=1)
              if (numbers and _numbers(fragment) & numbers)
              or (stems and stems <= _stems(fragment))])
    for number in _numbers(answer):
        sole([i for i, fragment in enumerate(fragments, start=1)
              if number in _numbers(fragment)])
    return owners


def grounded_fragments(answer: str, fragments: list[str]) -> tuple[int, ...]:
    """По каким фрагментам ответ РЕАЛЬНО собран — по содержанию, а не по
    словам модели о себе.

    Нужно по двум причинам сразу. Модель нередко пишет ответ и забывает
    строку со ссылками (живой прогон 388: «Дай ссылку на мой канал B17»
    — ответ был, формат не выдержан, и ответ отбрасывался целиком). И
    даже когда ссылки есть, они — утверждение модели, а не проверка.

    Различающим считается слово ответа, встречающееся ровно в ОДНОМ из
    показанных фрагментов: адрес, код услуги, фамилия. Общие слова
    («ссылки», «канал») есть везде и ничего не различают — они
    отсеиваются сами, без словаря стоп-слов, потому что критерий не
    «частое слово», а «слово, по которому фрагменты различаются».
    """
    per_fragment = [_tokens(fragment) for fragment in fragments]
    answer_tokens = _tokens(answer)
    distinctive = {token for token in answer_tokens
                   if sum(token in tokens for tokens in per_fragment) == 1}
    if distinctive:
        # Не «все, у кого есть хоть одно», а сильнейшие, и вес слова —
        # его длина: одна случайная словоформа («ссылку») не должна
        # уравнивать посторонний фрагмент с тем, где стоит сам адрес
        # («www.b17.ru/eliah»). Длина здесь — грубая мера того, насколько
        # слово вообще опознаёт источник.
        scores = [sum(len(token) for token in tokens & distinctive)
                  for tokens in per_fragment]
        best = max(scores)
        # НЕ «только сильнейший»: ответ, собранный из двух документов,
        # называл один. Точного равенства весов между двумя настоящими
        # источниками почти не бывает, и второй молча пропадал — а
        # владельцу показывали ответ с половиной его происхождения.
        # Половина лучшего веса разделяет эти два случая: случайная
        # словоформа («ссылку», вес 6) против самого адреса
        # («www.b17.ru/eliah», вес 16) — 6 < 8, фрагмент отсеивается;
        # два документа, каждый со своим именем или значением, весят
        # сопоставимо и остаются оба.
        # Порог веса — про то, какой фрагмент похож на ответ целиком.
        # Единоличные носители значений добавляются к нему, а не
        # проходят через него: у каждого утверждения своё доказательство.
        heavy = {i for i, score in enumerate(scores, start=1)
                 if score > 0 and score * 2 >= best}
        return tuple(sorted(heavy | _value_owners(answer, fragments)))
    # Различающих слов нет — берутся фрагменты с наибольшим пересечением.
    overlaps = [len(tokens & answer_tokens) for tokens in per_fragment]
    best = max(overlaps, default=0)
    if best == 0:
        return ()
    return tuple(i for i, count in enumerate(overlaps, start=1) if count == best)


#: Отброшенный ответ — это НЕ «модели не было». Разница видна
#: владельцу: при недоступной модели откат на ближайшую цитату честен
#: (мы просто не читали фрагменты), а при отброшенном ответе — нет.
#: Живой прогон 419: заземление отбросило выдуманный срок загранпаспорта,
#: probe откатился на детерминированный composer, и на «до какого числа
#: действует загран» пришло «Ближайшее из ваших записей: Антитела к
#: фактору Кастла 0.5 Ед/мл». Модель прочитала все пять фрагментов и не
#: смогла собрать проверяемый ответ; механическая «ближайшая» цитата из
#: тех же пяти не добавляет к этому ничего, кроме шума.
#:
#: Поэтому отброшенный ответ возвращается тем же исходом, что и честное
#: «НЕТ ОТВЕТА» модели: причины разные, вывод для владельца один — в
#: найденном ответа нет, вот что смотрели.


@dataclass(frozen=True)
class Synthesis:
    """Результат синтеза. `answered=False` — модель прочитала фрагменты
    и говорит, что ответа в них нет; это исход, а не ошибка."""

    answered: bool
    text: str = ""
    #: Номера фрагментов (1-based, как в промпте), на которые сослалась
    #: модель. Пусто при `answered=False`.
    used: tuple[int, ...] = ()
    #: `False` — ответ БЫЛ, но не прошёл проверку. Это не то же самое,
    #: что «модель прочитала и говорит, что ответа нет», и владельцу
    #: показывать это одинаково нельзя: в первом случае в документах
    #: что-то есть и мы не смогли это подтвердить, во втором — там
    #: действительно нет ответа.
    verified: bool = True


#: Единственный экземпляр «прочитано, показывать нечего» — см. выше.
_REJECTED = Synthesis(answered=False, verified=False)


def relevant_window(question: str, fragment: str,
                    width: int = MAX_FRAGMENT_CHARS) -> str:
    """Окно фрагмента ВОКРУГ слов вопроса, а не первые N символов.

    Распоряжение владельца 07.09.2026, п.2: «Не обрезай каждый фрагмент
    механически первыми 900 символами». Механическая обрезка отбрасывала
    ровно то, что искали: в лабораторном бланке первые сотни символов —
    шапка учреждения и номер заказа, а значение с единицей стоит ниже.

    Окно двигается по границам строк, а не по символам: строка таблицы
    не разрывается посередине. Если фрагмент и так короче ширины —
    возвращается целиком, и это самый частый случай.
    """
    text = fragment.strip()
    if len(text) <= width:
        return text
    wanted = {word[:_STEM_LEN] for word in _ANY_WORD_RE.findall(question.lower())
              if len(word) >= 4}
    if not wanted:
        return text[:width]

    lines = text.splitlines(keepends=True)
    scores = [sum(1 for w in _ANY_WORD_RE.findall(line.lower()) if w[:_STEM_LEN] in wanted)
              for line in lines]
    if not any(scores):
        return text[:width]

    # Лучшее окно подряд идущих строк, укладывающееся в ширину.
    best_start, best_score, start = 0, -1, 0
    size = 0
    score = 0
    for end, line in enumerate(lines):
        size += len(line)
        score += scores[end]
        while size > width and start < end:
            size -= len(lines[start])
            score -= scores[start]
            start += 1
        if score > best_score:
            best_start, best_score = start, score
            best_end = end
    window = "".join(lines[best_start:best_end + 1])[:width]
    prefix = "…" if best_start else ""
    suffix = "…" if best_end < len(lines) - 1 else ""
    return f"{prefix}{window.strip()}{suffix}"


def build_prompt(question: str, fragments: list[str]) -> str:
    numbered = "\n\n".join(
        f"[{i}] {relevant_window(question, text)}"
        for i, text in enumerate(fragments, start=1)
    )
    return (
        f"Вопрос: {question}\n\n"
        f"Фрагменты из документов пользователя:\n{numbered}\n\n"
        "Ответь на вопрос, используя только эти фрагменты. Если в них "
        "есть точное значение (адрес, число, дата, название) — приведи "
        "его дословно.\n"
        "Последней строкой напиши номера использованных фрагментов: "
        "ФРАГМЕНТЫ: 1,2\n"
        "Если ответа во фрагментах нет, напиши ровно одну строку: НЕТ ОТВЕТА"
    )


def parse_response(raw: str, *, fragments: list[str],
                   sources: list[str] | None = None) -> Synthesis | None:
    """Разобрать ответ модели. `None` — формат не выдержан, доверять нечему.

    `fragments` — что видела модель, `sources` — по чему её проверяют.
    Это РАЗНЫЕ вещи, и живой ответ 07.09.2026 показал, чем оборачивается
    их смешение: `probe._dated_fragment()` подписывает каждый фрагмент
    датой документа («(документ от 22.08.2026) …»), чтобы модель могла
    отвечать «в последний раз». Проверка чисел сверяла ответ с этой же
    подписью — и дата, дописанная нами, стала доказательством самой
    себя. На «до какого числа действует загран» пришло «до 22.08.2026»
    с источником «Эндоскопия.pdf», где такого срока нет вовсе.

    По умолчанию `sources = fragments` — вызывающему, который ничего к
    фрагментам не дописывал, разделять нечего.
    """
    fragment_count = len(fragments)
    sources = fragments if sources is None else sources
    text = (raw or "").strip()
    if not text:
        return None

    # Строк со ссылками бывает больше одной (модель повторяет формат
    # после каждого абзаца) — берутся все номера, и все такие строки
    # убираются из текста ответа: это разметка, а не ответ.
    matches = list(_CITATION_RE.finditer(text))
    claimed = tuple(sorted({
        n
        for match in matches
        for n in (int(part) for part in re.findall(r"\d+", match.group(1)))
        if 1 <= n <= fragment_count
    }))
    body = _CITATION_RE.sub(" ", text)
    body = re.sub(r"[ \t]{2,}", " ", body).strip(" \t\n.")

    if not body:
        return None
    if _CITATION_LEFTOVER_RE.search(body):
        logger.warning("синтез отброшен: маркер цитирования не разобран")
        return _REJECTED
    if _NO_ANSWER_RE.search(body) and not claimed:
        return Synthesis(answered=False)

    invented = ungrounded_numbers(body, sources)
    if invented:
        # Не «показать с оговоркой»: число, которого нет в источнике, —
        # это и есть выдумка, а выдумка с источником хуже отказа.
        logger.warning("синтез отброшен: чисел нет в источниках: %s", sorted(invented))
        return _REJECTED

    unbound = unbound_claims(body, sources)
    if unbound:
        # Значение во фрагментах есть, но принадлежит другому объекту.
        # Худший вид выдумки: она проходит проверку цифр и слов и
        # приходит с честно названным источником.
        logger.warning("синтез отброшен: значения при чужом объекте: %s", sorted(unbound))
        return _REJECTED

    invented_definitions = undefined_subjects(body, sources)
    if invented_definitions:
        # Слова из источника, источник назван честно — и всё равно чужое
        # утверждение: описание частного случая выдано за определение
        # целого (прогон 445).
        logger.warning("синтез отброшен: определения нет в источниках: %s",
                       sorted(invented_definitions))
        return _REJECTED

    unknown = ungrounded_words(body, sources)
    if unknown:
        logger.warning("синтез отброшен: названий нет в источниках: %s", sorted(unknown))
        return _REJECTED

    # Заземление по содержанию — главное, ссылки модели — уточнение.
    # Пересечение, если оно непусто: модель могла сослаться и на лишний
    # фрагмент, из которого в ответе ничего нет.
    grounded = grounded_fragments(body, sources)
    used = tuple(sorted(set(claimed) & set(grounded))) or grounded or claimed
    if not used:
        # Ответ не опирается ни на один показанный фрагмент. Проверить
        # его нечем — значит, показывать нельзя.
        return _REJECTED
    return Synthesis(answered=True, text=body, used=used)


def synthesize_or_none(question: str, fragments: list[str],
                       *, sources: list[str] | None = None) -> Synthesis | None:
    """Fail-open обёртка для probe.py — см. докстринг модуля.

    `sources` — исходный текст тех же фрагментов, без наших приписок;
    по нему, а не по показанному, проверяется заземление ответа (см.
    `parse_response()`). Обрезается тем же `MAX_FRAGMENT_CHARS`: за
    пределами окна модель ничего не видела, и засчитывать это ей в
    доказательства нельзя."""
    if not fragments:
        return None
    body = {
        "model": MODEL_NAME,
        "prompt": build_prompt(question, fragments),
        "system": SYSTEM_PROMPT,
        "stream": False,
        "keep_alive": KEEP_ALIVE,
    }
    req = urllib.request.Request(
        OLLAMA_URL, data=json.dumps(body).encode("utf-8"), method="POST",
        headers={"Content-Type": "application/json"},
    )
    try:
        # Ворота (`model_gate.py`): живой вопрос заявляет намерение, и
        # фоновый разбор уступает ему модель. Ждём освобождения недолго
        # и в любом случае идём дальше — ответ не должен зависеть от
        # исправности замка.
        with interactive_call():
            with urllib.request.urlopen(req, timeout=REQUEST_TIMEOUT) as resp:
                result = json.loads(resp.read().decode())
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as exc:
        logger.warning("локальный синтез недоступен, откат на composer: %s", exc)
        return None
    # Заземление сверяется по ТОМУ ЖЕ окну, которое видела модель:
    # доказательством не может быть текст за его пределами.
    trimmed = (None if sources is None
               else [relevant_window(question, t) for t in sources])
    return parse_response(result.get("response") or "", fragments=fragments, sources=trimmed)
