"""О чьих данных вопрос: о данных владельца или вообще.

Заведено 06.09.2026 по распоряжению владельца: «Отсутствие находок не
является моим разрешением оплатить ответ». До этого пустой поиск давал
`NEEDS_REASONING`, и вопрос уходил в платную модель, которая историю
владельца не знает и заполняла пустоту рассуждениями.

ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ЗАПРЕТИТЬ ОПЛАТУ ПРИ ПУСТОМ ПОИСКЕ. Тогда без
ответа остались бы и «переведи текст», и «что такое ферритин» — вопросы,
к личным данным не относящиеся, по которым локальной памяти и не должно
быть что сказать. Разбор 05.09.2026 (§5 CHUNKING_AND_BAD_ANSWERS) это
уже отмечал и откладывал до QuerySpec. Дальше откладывать нельзя, а
полного QuerySpec ещё нет — поэтому здесь ровно одно решение, которое
нужно сейчас: адресован вопрос личным данным или нет.

ЦЕНА ОШИБКИ НЕСИММЕТРИЧНА, И ПРАВИЛО СМЕЩЕНО НАМЕРЕННО. Ложно признать
вопрос личным — значит не заплатить за ответ, который платная модель
могла бы дать: владелец видит честное «в ваших записях этого нет».
Ложно признать личный вопрос общим — значит заплатить за выдумку о
здоровье владельца. Второе хуже, поэтому сомнение решается в пользу
«личный».

ЧЕГО ЗДЕСЬ НЕТ. Никакой модели и никакого разбора смысла: это список
признаков, снятых с формы вопроса. Полное определение области запроса —
работа QuerySpec (P4), и этот модуль ему не замена, а тот минимум, без
которого запрет оплаты нельзя включить, не сломав общие вопросы.
"""

from __future__ import annotations

import re

#: Притяжательные и личные обороты, прямо указывающие на данные
#: владельца. «Мне»/«меня»/«я» сами по себе НЕ признак: «переведи мне
#: текст» — дательный выгоды, а не владение данными.
_POSSESSIVE_RE = re.compile(
    r"\bу\s+меня\b|"
    r"\bмо[йяеёиюа][а-яё]*\b|"          # мой, моя, мои, моих, моей, моём…
    r"\bмне\s+(назначил\w*|прописал\w*|поставил\w*|выписал\w*|"
    r"рекомендовал\w*|делал\w*|ставил\w*)|"
    r"\bменя\s+(лечил\w*|наблюдал\w*|направил\w*|обследовал\w*|"
    r"оперировал\w*|консультировал\w*)|"
    r"\bя\s+(сдавал\w*|сдала|принимаю|принимал\w*|пью|пил\w*|был\w*|"
    r"ходил\w*|посещал\w*|посетил\w*|делал\w*|проходил\w*|лечил\w*|"
    r"обращал\w*|наблюдал\w*|работал\w*|учил\w*|жил\w*)",
    re.IGNORECASE)

#: Слова, по которым видно, что речь о записи в памяти, а не о мире.
#: Нужны в паре с указательным «что там»: «что там прописал врач»
#: указывает на документ, «что там в новостях» — нет.
#: Расширен 06.09.2026 по разбору владельца: «Что назначил кардиолог?»
#: и «Какие решения приняты по подзадачам в ШАГАХ?» не попадали сюда
#: вовсе — не было ни специальностей врачей, ни глаголов назначения в
#: личной форме, ни слов рабочего документа. Обе фразы про запись, а не
#: про мир, и платная модель ответа на них не знает.
#:
#: `\w+олог` с падежными окончаниями, а не `\w*олог\w*`: так сюда
#: попадает «кардиолог/кардиологу/кардиологом» и не попадает
#: «биология/биологии» — название науки признаком записи не является.
_RECORD_WORD_RE = re.compile(
    r"\bврач\w*|\bанализ\w*|\bприём\w*|\bприем\w*|\bзаключени\w*|"
    r"\bдокумент\w*|\bвыписк\w*|\bрезультат\w*|\bобследован\w*|"
    r"\bназначен\w*|\bпрописал\w*|\bдиагноз\w*|\bисследовани\w*|"
    r"\bсправк\w*|\bрезюме\b|\bдоговор\w*|\bчек-лист\w*|\bтз\b|"
    r"\bзаметк\w*|\bзапис\w*|\bуровен\w*|\bпоказател\w*|"
    r"\b\w+олог(?:а|у|ом|е|и|ов|ам|ами|ах)?\b|"
    r"\bдоктор\w*|\bтерапевт\w*|\bхирург\w*|\bфельдшер\w*|"
    r"\bназначи\w*|\bрекомендова\w*|\bвыписа\w*|\bпрописыва\w*|"
    r"\bподзадач\w*",
    re.IGNORECASE)

#: Указание на уже обсуждавшийся документ.
_DEICTIC_RE = re.compile(r"\bчто\s+там\b|\bтам\s+же\b|\bв\s+нём\b|\bв\s+этом\s+документе\b",
                         re.IGNORECASE)

#: Прямая отсылка к хранилищу.
_STORE_RE = re.compile(
    r"\bв\s+(моих|своих)\s+\w+|\bв\s+памяти\b|\bв\s+записях\b|"
    r"\bиз\s+(моих|своих)\s+\w+|\bпо\s+моим\s+\w+",
    re.IGNORECASE)


def is_personal_data_question(query: str) -> bool:
    """Адресован ли вопрос данным владельца.

    `True` означает ровно одно: платной модели этот вопрос отдавать
    нельзя, потому что она этих данных не знает. Не означает, что ответ
    в памяти есть.
    """
    if _STORE_RE.search(query) or _POSSESSIVE_RE.search(query):
        return True
    return bool(_DEICTIC_RE.search(query) and _RECORD_WORD_RE.search(query))


#: Вопрос ли это по форме. Нужно ровно для одного решения — продолжает
#: ли сообщение разговор о памяти (см. `query_spec.classify_mode`):
#: вопрос после ответа из памяти продолжает его, «переведи текст» —
#: нет, это новое поручение.
#: `-то`, `-нибудь`, `-либо` превращают вопросительное слово в
#: неопределённое: «какой-то обычный текст» — не вопрос, а начало
#: заметки. Без оговорки надиктованное становилось вопросом (поймано
#: тестом `test_process_voice_pending_non_remember_saves_transcript_and_sends_menu`).
_INDEFINITE_TAIL = r"(?!-(?:то|нибудь|либо)\b)"

_QUESTION_WORD_RE = re.compile(
    r"^\s*(?:а\s+|и\s+|ну\s+)?(?:что|чем|чего|как(?:ой|ая|ое|ие|их|им|ом)?|"
    r"где|когда|кто|кого|кому|почему|зачем|сколько|куда|откуда|разве|правда\s+ли)"
    + _INDEFINITE_TAIL + r"\b",
    re.IGNORECASE)


def is_question(text: str) -> bool:
    return "?" in text or bool(_QUESTION_WORD_RE.match(text))


#: Просьба достать сведения без вопросительного слова: «напомни
#: название книжки», «найди выписку», «скажи, что там было».
_REQUEST_VERB_RE = re.compile(
    r"\b(?:напомни(?:те)?|найди(?:те)?|скажи(?:те)?|покажи(?:те)?|"
    r"подскажи(?:те)?|перечисли(?:те)?|расскажи(?:те)?)\b", re.IGNORECASE)

#: Вопросительное слово НЕ первым: «Слушай, а какой у меня был
#: холестерин». Список уже, чем у `_QUESTION_WORD_RE`: «как» исключено
#: намеренно — в середине фразы это чаще союз («купи молоко, как
#: договорились»), и по нему заметка становилась бы вопросом.
_QUESTION_WORD_INSIDE_RE = re.compile(
    r"\b(?:что|чего|как(?:ой|ая|ое|ие|их|им|ом)|где|когда|кто|кого|кому|"
    r"почему|зачем|сколько|куда|откуда)" + _INDEFINITE_TAIL + r"\b",
    re.IGNORECASE)

#: Сколько первых слов считаются началом фразы.
_HEAD_WORDS = 5


def is_information_request(text: str) -> bool:
    """Обращение за сведениями, а не надиктованная заметка.

    ЗАЧЕМ ОТДЕЛЬНО ОТ `is_question()`. Тот привязан к началу строки и
    требует «?» или вопросительного слова первым. Расшифровка речи не
    несёт знаков препинания вовсе, а вопросительное слово в живой речи
    стоит не первым: «Слушай, а какой у меня был холестерин».

    ДЛЯ ЧЕГО НУЖНО. Разбор владельца 07.09.2026: голосовой вопрос, на
    который поиск ничего не нашёл, автоматически превращался в
    предложение сохранить документ. Намерение спросить и намерение
    сохранить обязаны различаться ПО САМОЙ ФРАЗЕ, а не по тому, повезло
    ли поиску.
    """
    head = " ".join((text or "").split()[:_HEAD_WORDS])
    return (is_question(text or "")
            or bool(_QUESTION_WORD_INSIDE_RE.search(head))
            or bool(_REQUEST_VERB_RE.search(text or "")))
