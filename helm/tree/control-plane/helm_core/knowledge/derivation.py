"""Производная ревизия: что именно делает разбор тех же байтов другим.

ЗАЧЕМ. `knowledge_semantic_jobs` считает работу сделанной по четвёрке
«пользователь, источник, содержимое, версия». Содержимое — sha256 файла.
Значит одни и те же байты после ИСПРАВЛЕНИЯ ПАРСЕРА попадают в тот же
ключ и повторно не разбираются: очередь считает, что эта работа уже
выполнена, хотя выполнена она прежним, сломанным способом.

Ровно это и случилось 07.09.2026. `parsers.py` не умел fb2 и отдавал
книгу как один кусок XML-разметки; после починки те же байты дают 1399
фрагментов вместо одного. Ничто в схеме об этом не знало — переразбор
пришлось запускать правкой статуса задания руками.

РЕШЕНИЕ — ОДНО ЧИСЛО И ОДНА ПРОВЕРКА. Версия остаётся одна
(`semantic_publish.SEMANTIC_VERSION`), она же ключ переразбора: подъём
версии автоматически делает всю прежнюю работу невыполненной и ставит
новые задания. Добавляется только то, чего не хватало, — механизм,
который НЕ ДАЁТ ЗАБЫТЬ её поднять.

Отпечаток берётся по структуре кода, а не по тексту файла: комментарий
или перенос строки версию не двигают, а любое изменение поведения
двигает. Считается по `ast.dump()` разобранного модуля со снятыми
докстрингами — то есть по тому, что модуль ДЕЛАЕТ.

ЧТО ВХОДИТ В ОТПЕЧАТОК. Разбор файла в текст, нарезка текста на чанки и
нарезка текста на окна — три шага, которые из одних байтов делают разный
вход для извлечения. Сам контракт извлечения (`semantic_extract`,
`semantic_publish`) сюда НЕ входит: он и так версионируется вручную и
этим порядком живёт с R2, а класть его в автоматический отпечаток
значило бы поднимать версию корпуса на каждую правку публикации.
"""

from __future__ import annotations

import ast
import hashlib
from pathlib import Path

#: Модули, изменение которых меняет производную того же файла.
DERIVING_MODULES = ("parsers.py", "tables.py", "chunking.py", "semantic_windows.py")

#: Отпечаток, при котором объявленная версия признана согласованной.
#: Ключ — `SEMANTIC_VERSION`, значение — `derivation_fingerprint()`.
#:
#: СТРОКА ВЫКАЧЕННОЙ ВЕРСИИ НЕ ПРАВИТСЯ. Изменил парсер, восстановление
#: таблиц, чанкинг или окна — подними версию и добавь НОВУЮ строку.
#: Переписать строку версии, под которой уже разобран корпус, значит
#: сказать, что разобранное прежним способом разобрано нынешним, — а это
#: ровно та неправда, против которой заведён весь этот модуль.
#:
#: Единственное исключение — версия, под которой ещё ничего не
#: разобрано. Пока она не выкачена, её отпечаток уточняется правкой: о
#: корпусе он ничего не утверждает. Как только под версией появилась
#: хоть одна ревизия, строка замерзает.
RECORDED_FINGERPRINTS: dict[int, str] = {
    # 07.09.2026: fb2-ветка в parsers.py и деление переполненных блоков
    # в chunking.py. Записано как базовая линия v3 — см. докстринг теста
    # `test_declared_version_matches_the_deriving_code`.
    3: "7aef2e1e58ad1cb9e297fab7022643cbd90739a5a184d3a8641ff3b6ac2558e4",
    # 08.09.2026: восстановление строк таблицы при разборе (`tables.py`,
    # вызывается из `parse_file`). Те же байты лабораторного PDF теперь
    # дают текст, где название, значение, единица и референсный диапазон
    # стоят на одной строке, — то есть ДРУГОЙ вход для чанкинга и
    # извлечения. Первый случай, ради которого этот механизм и заведён:
    # без подъёма версии очередь считала бы работу по прежнему парсеру
    # выполненной.
    4: "adf19dd724395df5ddab6a4ab0eb9082e4cffc0a7f73a0b0ce81a7fec1e90784",
}


def _structure(path: Path) -> str:
    """Структура модуля без докстрингов: что он делает, а не как описан."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.ClassDef,
                                 ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        body = node.body
        if (body and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)):
            node.body = body[1:] or [ast.Pass()]
    return ast.dump(tree, annotate_fields=False)


def derivation_fingerprint() -> str:
    """Отпечаток кода, превращающего байты файла в вход для извлечения."""
    here = Path(__file__).parent
    digest = hashlib.sha256()
    for name in DERIVING_MODULES:
        digest.update(name.encode("utf-8"))
        digest.update(_structure(here / name).encode("utf-8"))
    return digest.hexdigest()
