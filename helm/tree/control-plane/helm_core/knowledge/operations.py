"""Операции над найденным: что именно исполнитель должен сделать.

Распоряжение владельца 07.09.2026, п.3: «Сейчас наличие объекта
QuerySpec опережает возможности исполнителя. В общем пути тип операции
фактически не управляет ответом». Так и было: `intent` описывал, КАКОЙ
ответ считается ответом, но на исполнение не влиял — всё сводилось к
одному действию «покажи подходящий фрагмент».

Здесь заводится первая пара операций, которые он назвал первыми:

* «сколько» возвращает КОЛИЧЕСТВО, рассчитанное по найденному набору;
* «все» обходит полный подходящий набор либо прямо говорит о неполноте.

Обе детерминированные: ни одна не зовёт модель. Число, полученное
пересчётом, не может быть выдумано — а именно выдумка значений была
главным дефектом прошлых прогонов.

ЧТО ЭТО НЕ СЛОВАРЬ ТЕМ. Владелец запретил чинить разбор добавлением
слов вроде «беру» и «прилёт» — слов ПРЕДМЕТА. «Сколько» и «все» — слова
ОПЕРАЦИИ, и он сам определил их через требуемое поведение. Предмет
по-прежнему решает поиск, не регулярное выражение.

ЧЕГО ЗДЕСЬ НЕТ. Границы отдельных пунктов списка в ответ не выносятся:
разметки списков на приёме ещё нет (п.6), и восстанавливать её по
запятым значило бы показывать владельцу свою догадку как его данные.
Поэтому перечисление отдаёт исходное предложение дословно, а счёт —
число, полученное по разделителям в нём. Ограничение названное.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Значение, пункт, дата — то, что исполнялось и раньше: показать
#: подходящее. Умолчание, когда операция не названа.
OP_VALUE = "value"
OP_COUNT = "count"
OP_ENUMERATE = "enumerate"
#: Требуемая ФОРМА ответа. Отличается от `count`/`enumerate` тем, что
#: не считает и не обходит набор, а решает, КАКОЙ из найденных
#: фрагментов вообще годится в ответ: на «что такое X» годится тот, где
#: X определяют, а не тот, где X упомянут.
OP_DEFINE = "define"
OP_EXAMPLE = "example"

_COUNT_RE = re.compile(r"\bсколько\b|\bколичество\b|\bкол-во\b", re.IGNORECASE)
_ENUMERATE_RE = re.compile(
    r"\bвсе\b|\bвсех\b|\bвсё\b|\bперечисли(?:те)?\b|\bсписок\b|\bкаждый\b",
    re.IGNORECASE)
_DEFINE_RE = re.compile(
    r"\bчто\s+так(?:ое|ой|ая)\b|\bкто\s+так(?:ой|ая|ие)\b|"
    r"\bчто\s+знач(?:ит|ат)\b|\bопределени\w*\b",
    re.IGNORECASE)
_EXAMPLE_Q_RE = re.compile(r"\bпример(?:ы|ов|а|ами)?\b|\bнапример\b", re.IGNORECASE)

#: ПРИЗНАКИ ФОРМЫ В ТЕКСТЕ — грамматические конструкции, а не слова
#: предмета. «X — это Y», «X называется Y», «под X понимают Y» — так
#: выглядит определение в русском тексте независимо от того, что такое
#: X. Тот же класс, что «сколько» и «все» у операций.
#:
#: «это» засчитывается только после тире: без него оно стоит в каждом
#: втором предложении и определением не является.
_DEFINITION_MARK_RE = re.compile(
    r"[—–-]\s*это\b|\bназыва(?:ется|ются|ют)\b|\bименуется\b|"
    r"\bпредставляет\s+собой\b|\bопределяется\s+как\b|\bпонима(?:ется|ют)\b",
    re.IGNORECASE)
_EXAMPLE_MARK_RE = re.compile(
    r"\bнапример\b|\bк\s+примеру\b|\bпример(?:ы|ов|а|ом|е)?\b|"
    r"\bслучай\s+из\b|\bрассмотрим\b|\bпривед(?:ём|ем)\b",
    re.IGNORECASE)

#: Какая конструкция обязана стоять во фрагменте, чтобы он годился под
#: требуемую форму ответа. Операции, которых здесь нет, форму не
#: требуют и порядок фрагментов не меняют.
_FORM_MARKS = {OP_DEFINE: _DEFINITION_MARK_RE, OP_EXAMPLE: _EXAMPLE_MARK_RE}

#: Как назвать владельцу отсутствие требуемой формы. Не «ничего не
#: нашёл»: фрагменты есть, в них нет определения — это разные вещи.
FORM_MISSING_NOTICE = {
    OP_DEFINE: "Определения в ваших записях я не нашёл — показываю ближайшее упоминание.",
    OP_EXAMPLE: "Примеров в ваших записях я не нашёл — показываю ближайшее упоминание.",
}

#: Разделители перечисления. Точка с запятой и «и» перед последним
#: элементом — то же перечисление, что запятая.
_ITEM_SPLIT_RE = re.compile(r"\s*[,;]\s*|\s+и\s+", re.IGNORECASE)
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+|\n+")
_WORD_RE = re.compile(r"[0-9a-zа-яё]+", re.IGNORECASE)
_STEM_LEN = 5
#: Служебные слова, по которым совпадать нельзя. Закрытый
#: грамматический класс — местоимения и количественные слова, — а не
#: словарь предмета: предмет по-прежнему решает поиск.
#:
#: Заведено живым прогоном 427: «сколько у меня каналов» совпало с
#: фразой из книги «В результате двухлетней терапии она сказала: „У
#: МЕНЯ, конечно, остались проблемы…"» по слову «меня» — и выдало
#: «Насчитал 6» по чужому тексту.
_FUNCTION_STEMS = frozenset({
    "меня", "мне", "мной", "мой", "моя", "моё", "мои", "моих", "моим",
    "себя", "тебя", "него", "неё", "них", "нами", "вами",
    "всего", "всех", "все", "всё", "этот", "эта", "это", "этом", "того",
    "тому", "там", "тогда", "когда", "какой", "какие", "каких", "сколь",
    "может", "были", "было", "быть",
})

#: Перечислением считается предложение хотя бы с двумя разделителями:
#: одна запятая бывает в любой фразе, две подряд — уже список.
MIN_ITEMS = 3


def detect_operation(question: str) -> str:
    """Какую операцию просит вопрос. Счёт проверяется раньше
    перечисления: «сколько всего пунктов» — это счёт, хотя «всего» тоже
    слово перечисления."""
    if _COUNT_RE.search(question):
        return OP_COUNT
    # Форма ответа проверяется РАНЬШЕ перечисления: «дай все примеры» —
    # это просьба о примерах, и слово «все» её не переопределяет.
    if _DEFINE_RE.search(question):
        return OP_DEFINE
    if _EXAMPLE_Q_RE.search(question):
        return OP_EXAMPLE
    if _ENUMERATE_RE.search(question):
        return OP_ENUMERATE
    return OP_VALUE


@dataclass(frozen=True)
class Enumeration:
    """Перечисление, найденное в тексте дословно."""

    sentence: str
    items: tuple[str, ...]

    @property
    def count(self) -> int:
        return len(self.items)


def _stems(text: str) -> set[str]:
    return {word.lower()[:_STEM_LEN] for word in _WORD_RE.findall(text)}


def _items_of(sentence: str) -> tuple[str, ...]:
    """Пункты перечисления — или пусто, если границу списка не видно.

    ГРАНИЦА ВАЖНЕЕ РАЗДЕЛИТЕЛЕЙ. Первый замер этой функции дал «насчитал
    5» на «Запомнив дорожную аптечку, я кладу ибопрофен, лаперамид,
    пластырь и антисептик» — пунктов там четыре, а пятым посчиталась
    вводная часть предложения. Уверенное неправильное число — ровно тот
    дефект, который закрывался всю неделю, и повторять его в новом месте
    нельзя.

    Поэтому считаем только там, где начало списка ВИДНО:

    * есть двоеточие — список начинается после него;
    * двоеточия нет, но все элементы короткие (≤2 слов) — вводной части
      в предложении нет, оно всё и есть перечисление.

    Иначе — пусто: границу пришлось бы угадывать. Надёжно её даст
    разметка списков на приёме (п.6 распоряжения), и до неё «сколько»
    честно говорит, что посчитать не может.
    """
    body = sentence.rsplit(":", 1)[-1] if ":" in sentence else sentence
    parts = [part.strip(" .!?…") for part in _ITEM_SPLIT_RE.split(body)]
    items = tuple(part for part in parts if len(part) > 1)
    if len(items) < MIN_ITEMS:
        return ()
    if ":" in sentence:
        return items
    if all(len(_WORD_RE.findall(item)) <= 2 for item in items):
        return items
    return ()


def _line_list(text: str) -> Enumeration | None:
    """Список, разложенный ПО СТРОКАМ: строка с двоеточием на конце и
    идущие за ней непустые строки.

    Без этого счёт не работал на самой обычной форме списка. ИЗМЕРЕНО
    07.09.2026 на записи владельца «ссылки на мои каналы:» с девятью
    строками под ней: `_SENTENCE_SPLIT_RE` режет текст по переводу
    строки, каждая строка становилась отдельным «предложением» без
    разделителей, и `_items_of()` не находил в них ничего. На вопрос
    «сколько у меня каналов» исполнитель отказывался считать, и ответом
    шёл сам список — верный расчёт был отброшен на ровном месте.

    Граница та же, что и у `_items_of()`, и по той же причине: список
    начинается после двоеточия НА КОНЦЕ строки. Двоеточие посреди фразы
    («она сказала: „…"») границей не считается — иначе цитата снова
    станет списком.
    """
    lines = [line.strip() for line in text.splitlines()]
    for i, line in enumerate(lines):
        if not line.endswith(":"):
            continue
        items: list[str] = []
        for candidate in lines[i + 1:]:
            if not candidate:
                break
            items.append(candidate)
        if len(items) >= MIN_ITEMS:
            return Enumeration(f"{line}\n" + "\n".join(items), tuple(items))
    return None


def find_enumeration(question: str, text: str) -> Enumeration | None:
    """Предложение-перечисление, ближайшее к вопросу по словам.

    Ближайшее, а не первое: в лабораторном бланке перечислений много, и
    брать любое значило бы отвечать о чужой строке.
    """
    wanted = {stem for stem in _stems(question)
              if len(stem) >= 4 and stem not in _FUNCTION_STEMS}
    best: Enumeration | None = None
    best_score = 0
    for sentence in _SENTENCE_SPLIT_RE.split(text):
        items = _items_of(sentence)
        if not items:
            continue
        # НОЛЬ ОБЩИХ СЛОВ — ОТКАЗ, а не «фрагмент же отобрали поиском».
        #
        # Первая версия принимала любое перечисление в отобранном
        # фрагменте. Живой прогон 427 показал цену немедленно: на
        # «сколько у меня каналов» пришло «Насчитал 6» по фразе из книги
        # Линде «В результате двухлетней терапии она сказала: „У меня,
        # конечно, остались проблемы, но я вспоминаю, какой я была, это
        # просто ужас!"» — двоеточие и запятые сделали цитату «списком».
        #
        # Уверенное неправильное число из чужого текста — ровно тот
        # дефект, который закрывался всю неделю, и я завёл его заново в
        # новом месте. Совпадение слов с ВОПРОСОМ обязательно: поиск
        # отбирает документ, но не предложение внутри него.
        score = len(_stems(sentence) & wanted)
        if score > best_score:
            best, best_score = Enumeration(sentence.strip(), items), score

    # Список в столбик — та же проверка совпадения с вопросом, что и у
    # списка в строку: границу видно, но принадлежность вопросу решает
    # не она.
    column = _line_list(text)
    if column is not None and len(_stems(column.sentence) & wanted) > best_score:
        best = column
    return best


@dataclass(frozen=True)
class FormSelection:
    """Порядок фрагментов под требуемую форму ответа."""

    #: Индексы исходного списка: сначала подходящие по форме.
    order: tuple[int, ...]
    #: Нашёлся ли хоть один фрагмент требуемой формы. `False` — ответ
    #: собирается из упоминаний, и сказать об этом обязательно.
    found: bool


def select_for_operation(operation: str, question: str,
                         texts: list[str]) -> FormSelection:
    """Поставить вперёд фрагменты той формы, которую требует вопрос.

    Распоряжение владельца 07.09.2026, п.3. Живой прогон 443: на «по
    книге Линде что такое эмоционально-образная терапия» поиск нашёл
    нужную книгу, но в доказательства попал раздел «Рекомендуемая
    литература» — фрагмент, где термин упомянут и не определён. Тип
    ответа не участвовал в отборе вовсе, фрагменты шли по рангу поиска.

    Отбор, а не фильтр: неподходящие по форме не выбрасываются, а
    уходят вниз. Определение может стоять не там, где его ждёт правило,
    и терять из-за этого весь ответ нельзя.

    Совпадение с вопросом обязательно — по той же причине и тем же
    способом, что в `find_enumeration()`: «например» в чужом абзаце
    примером к вопросу не становится.
    """
    mark = _FORM_MARKS.get(operation)
    if mark is None:
        return FormSelection(tuple(range(len(texts))), True)

    wanted = {stem for stem in _stems(question)
              if len(stem) >= 4 and stem not in _FUNCTION_STEMS}
    fitting, rest = [], []
    for index, text in enumerate(texts):
        matched = mark.search(text) and (not wanted or _stems(text) & wanted)
        (fitting if matched else rest).append(index)
    return FormSelection(tuple(fitting + rest), bool(fitting))


@dataclass(frozen=True)
class OperationAnswer:
    text: str
    #: Номера фрагментов (1-based), по которым получен ответ.
    used: tuple[int, ...]


def run_count(question: str, fragments: list[str]) -> OperationAnswer | None:
    """«Сколько» — число, полученное пересчётом, а не пересказом.

    `None` — перечисления в найденном нет, считать нечего; вызывающий
    честно говорит об этом, а не выдаёт ближайшее число из текста.
    """
    for index, text in enumerate(fragments, start=1):
        found = find_enumeration(question, text)
        if found is not None:
            return OperationAnswer(
                text=f"Насчитал {found.count}. Дословно из записи: «{found.sentence}»",
                used=(index,))
    return None


def run_enumerate(question: str, fragments: list[str], *,
                  complete: bool) -> OperationAnswer | None:
    """«Все» — обход всего подходящего набора, а не первой находки.

    `complete=False` — набор кандидатов упёрся в лимит поиска, и о
    неполноте говорится прямо: «все» без этой оговорки было бы
    утверждением, которого у нас нет.
    """
    lines: list[str] = []
    used: list[int] = []
    for index, text in enumerate(fragments, start=1):
        found = find_enumeration(question, text)
        if found is not None:
            lines.append(f"«{found.sentence}»")
            used.append(index)
    if not lines:
        return None
    body = "\n".join(lines)
    if not complete:
        body += ("\n\nПоказал не всё: найденного больше, чем помещается в один "
                 "просмотр. Уточните вопрос, чтобы сузить.")
    return OperationAnswer(text=body, used=tuple(used))
