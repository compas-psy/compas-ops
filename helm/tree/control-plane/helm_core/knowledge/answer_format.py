"""Компактный форматтер ответа (контракт владельца 05.09.2026).

Отдельный модуль, а не метод `DoctorsAnswer`, по одной причине: правила
изложения и правила доказательства меняются с разной скоростью и по
разным поводам. `query_router` отвечает за то, ЧТО доказано;
этот файл — только за то, КАК это сказано. Модель тут не участвует
вовсе: текст детерминирован, один и тот же ответ на один и тот же вход.

Контракт, дословно из распоряжения:

- прямой ответ первым, 1–4 коротких предложения;
- запрещено: рассказывать, как система искала; перечислять ограничения
  поиска; слова «документ/чанк/уверенность/граф/evidence», если о них не
  спрашивали; повторять вопрос; длинные вступления; «возможно/вероятно/
  похоже»; заполнять отсутствие ответа общими рассуждениями;
- нет доказанного ответа — сказать прямо и коротко.

Для вопроса о врачах порядок задан отдельно: СНАЧАЛА специальности,
ФИО и даты — вторым планом. Перечисление документов, исследований и
диагнозов — провал приёмки, поэтому их тут просто неоткуда взять:
на вход подаётся уже собранный `DoctorsAnswer`, в котором ничего этого
нет.
"""

from __future__ import annotations

import re

from .query_router import DoctorItem, DoctorsAnswer

#: Единственная форма отказа. Одна строка, без объяснений, почему не
#: нашлось: объяснение — это и есть «перечислять ограничения поиска».
NOT_FOUND = "Не нашёл в ваших данных подтверждённого ответа."

#: Ответ на вопрос о данных владельца, когда в памяти ничего нет.
#: Говорит и о том, что не нашлось, и о том, что за догадкой к платной
#: модели никто не пошёл: молчаливая оплата выглядела бы как обычный
#: ответ и не оставляла бы следа (распоряжение владельца 06.09.2026).
PERSONAL_NOT_FOUND = (
    "В ваших записях я такого не нашёл.\n"
    "К платной модели с вопросом о ваших данных не обращаюсь: она их "
    "не знает и ответила бы догадкой."
)

#: Дальше какого числа врачей поимённый список перестаёт быть коротким
#: ответом и становится перечислением. Пять — это ровно тот размер, на
#: котором Z1 в production уже читался как свалка (§1.1 отчёта
#: PRODUCTION_ANSWERS_RCA_2026-09-05.md).
_MAX_NAMED = 5


def _plural_doctors(count: int) -> str:
    """«1 врач», «2 врача», «5 врачей» — по последним цифрам числа."""
    tail_two = count % 100
    tail_one = count % 10
    if 11 <= tail_two <= 14 or tail_one == 0 or tail_one >= 5:
        return "врачей"
    if tail_one == 1:
        return "врач"
    return "врача"


def _named(item: DoctorItem) -> str:
    parts = [item.person]
    if item.specialties:
        parts.append(", ".join(item.specialties))
    if item.dates:
        parts.append(", ".join(item.dates))
    return " — ".join(parts) if len(parts) > 1 else parts[0]


def format_doctors(answer: DoctorsAnswer) -> str:
    """Текст ответа на «каких врачей я посещал».

    Врач с доказанной врачебной ролью, но без подтверждённой
    специальности, обязан присутствовать в ответе — он доказанный врач,
    просто без специальности. Молча выкинуть его из перечня
    специальностей и не сказать о нём ни слова значило бы ответить
    «двое» там, где доказано трое (дефект из распоряжения 05.09.2026).
    """
    if not answer.items:
        return _nothing_found(answer)

    specialties: list[str] = []
    for item in answer.items:
        for specialty in item.specialties:
            if specialty not in specialties:
                specialties.append(specialty)
    specialties.sort()

    unnamed = sum(1 for item in answer.items if not item.specialties)

    lines: list[str] = []
    if specialties:
        head = ", ".join(specialties)
        lines.append(head[0].upper() + head[1:] + ".")
    if unnamed:
        prefix = "Ещё" if specialties else "Есть"
        lines.append(f"{prefix} {unnamed} {_plural_doctors(unnamed)} "
                     "без подтверждённой специальности.")

    if len(answer.items) <= _MAX_NAMED:
        lines.append("; ".join(_named(item) for item in answer.items) + ".")
    else:
        lines.append(f"Всего {len(answer.items)} {_plural_doctors(len(answer.items))}.")
    if answer.year is not None and answer.undated_doctors:
        lines.append(f"Ещё {answer.undated_doctors} "
                     f"{_plural_doctors(answer.undated_doctors)} без подтверждённой "
                     "даты приёма — отнести к году нечем.")
    period = _period_not_applied(answer)
    if period:
        lines.append(period)
    return "\n".join(lines)


def _period_not_applied(answer: DoctorsAnswer) -> str | None:
    """Сказать вслух, что период из вопроса не применён.

    До 06.09.2026 такой ответ выглядел ответом на заданный вопрос:
    «в марте 2025» отбиралось по всему 2025 году, «за последний год» —
    вообще без отбора, и ни строчки об этом. Ответ, который сужен
    меньше, чем спросили, и молчит об этом, — неправда той же природы,
    что придуманная цифра (§5.1).
    """
    if not answer.unsupported_period:
        return None
    if answer.year is not None:
        return (f"Отобрал по {answer.year} году целиком: сузить до "
                f"«{answer.unsupported_period}» я пока не умею.")
    return (f"Ответ по всем вашим данным: ограничение "
            f"«{answer.unsupported_period}» я пока применять не умею.")


def _nothing_found(answer: DoctorsAnswer) -> str:
    """Пусто — говорим это прямо и с указанием года, если он был.

    Если при этом врачи в данных есть, но без дат, об этом сказано
    второй строкой. Умолчать было бы неправдой: «не нашёл за 2014»
    прочиталось бы как «врачей в данных нет», а они есть — просто
    привязать их к году нечем.
    """
    if answer.year is None:
        period = _period_not_applied(answer)
        return f"{NOT_FOUND}\n{period}" if period else NOT_FOUND
    text = ("Не нашёл в ваших данных подтверждённых посещений врачей "
            f"за {answer.year} год.")
    if answer.undated_doctors:
        count = answer.undated_doctors
        whom = "которого" if count % 10 == 1 and count % 100 != 11 else "которых"
        text += (f"\nВ данных есть {count} {_plural_doctors(count)}, "
                 f"дату приёма у {whom} подтвердить не удалось.")
    period = _period_not_applied(answer)
    if period:
        text += f"\n{period}"
    return text


def format_nearest_quote(quote: str, cite: str) -> str:
    """Замена перечислению «Найдено N совпадений».

    Несколько похожих фрагментов — это не ответ, а результат поиска, и
    выдавать их списком контракт запрещает прямо. Но и промолчать о
    найденном неправильно: ближайший фрагмент честно назван ближайшим, а
    не ответом, и он один.
    """
    return f"Не нашёл прямого ответа. Ближайшее из ваших записей:\n{quote}\n\nИсточник: {cite}"


#: Заголовок и пустая строка бланка — не ответ. НАЙДЕНО живым чатом
#: владельца 05.09.2026: на «что там прописал врач?» бот вернул
#: «Врач: Фамилия Имя Отчество ______», а до этого — «ОСМОТР
#: ГАСТРОЭНТЕРОЛОГА». Оба фрагмента формально прошли: они длиннее порога
#: MIN_LEXICAL_CHUNK_CHARS=20, потому что тот порог ставился по длине
#: РАНЕЕ пойманного мусора («Врач КДЛ:», 9 символов), а не по признаку.
#: Длина в символах вообще не отличает утверждение от шапки документа —
#: «ОСМОТР ГАСТРОЭНТЕРОЛОГА» это 24 символа.
#:
#: Замер корпуса (прогон 307): медиана чанка 65 символов, 519 из 953
#: короче 80, 390 не содержат конечной пунктуации. Единица поиска —
#: строка бланка, а не абзац; это чинится перечанкованием (P8.5.2, долг),
#: и здесь НЕ чинится. Здесь закрывается только то, что систему заставляет
#: врать: выдавать шапку за «ближайшее из ваших записей».
_PLACEHOLDER_RE = re.compile(r"_{3,}")
_HAS_LOWERCASE_RE = re.compile(r"[a-zа-яё]")
#: Утверждение — это подлежащее и что-то сказанное о нём. Четыре слова —
#: минимум, при котором фрагмент вообще может им быть; «Врач уролог:
#: Волков Алексей Романович» (5 слов) проходит и проходить должен,
#: «Дата: 24.08.2026 09:58» (3 слова) — нет.
_MIN_QUOTABLE_WORDS = 4


def is_quotable(text: str) -> bool:
    """Годится ли фрагмент на роль цитаты-ответа.

    Три признака, каждый отбраковывает свой вид не-ответа:
    прочерк-заполнитель — незаполненное поле формы; отсутствие строчных
    букв — шапка документа; меньше четырёх слов — подпись, код услуги,
    голая дата.

    Ложноотрицательные допускаются осознанно: «Диагноз: гастрит» будет
    отброшен. Контракт владельца от 05.09.2026 прямо предпочитает
    честное «не нашёл» ответу, который выглядит ответом и им не является.
    """
    stripped = text.strip()
    if _PLACEHOLDER_RE.search(stripped):
        return False
    if not _HAS_LOWERCASE_RE.search(stripped):
        return False
    return len(stripped.split()) >= _MIN_QUOTABLE_WORDS


def _cite_list(filenames: list[str]) -> str:
    """Имена источников без повторов, в порядке появления."""
    seen: list[str] = []
    for name in filenames:
        if name and name not in seen:
            seen.append(name)
    return ", ".join(seen)


def format_with_sources(answer: str, filenames: list[str], *,
                        unsupported_period: str | None = None) -> str:
    """Ответ + то, по чему он собран, + честно названное неприменённое
    условие. Источники печатаются всегда, когда они есть: без них ответ
    локальной модели нечем проверить (см. synthesis.py).

    `unsupported_period` — период из вопроса, который исполнитель
    применить не умеет. Тот же принцип, что уже действует в
    `format_doctors()`: молчаливое игнорирование условия — худший из
    вариантов, потому что ответ выглядит ответом на заданный вопрос.
    """
    parts = [answer.strip()]
    if unsupported_period:
        parts.append(f"Период «{unsupported_period}» я применить не умею — "
                     f"смотрел по всем записям.")
    cites = _cite_list(filenames)
    if cites:
        parts.append(f"Источники: {cites}")
    return "\n\n".join(parts)


def format_unknown_source(hint: str) -> str:
    """Вопрос назвал источник, которого в памяти нет.

    Поиск по всем записям здесь был бы ХУЖЕ отказа: владелец назвал
    документ, и ответ из другого документа — ровно тот дефект, ради
    которого ограничение источника и заводится. Молча проигнорировать
    условие тоже нельзя (тот же принцип, что у `unsupported_period`).
    """
    return (f"Вы назвали источник «{hint}», но документа с таким названием "
            f"я не нашёл — ни по имени файла, ни по тому, как документ "
            f"представляется в своём начале.\n\n"
            f"По всем записям искать не стал: это был бы ответ из другого "
            f"документа. Уточните название или спросите без него.")


def format_unverified(filenames: list[str]) -> str:
    """Ответ был, но проверку не прошёл — и это НЕ «данных нет».

    Распоряжение владельца 07.09.2026, п.4: «не подменяй отклонённый
    ответ утверждением, что информации в документах нет: это разные
    исходы». Разница для него практическая: «не нашёл» значит «ищи в
    другом месте», а «не смог подтвердить» значит «в этих документах,
    скорее всего, есть — открой их сам».
    """
    cites = _cite_list(filenames)
    text = ("Нашёл записи по вашему вопросу, но подтвердить ответ по ним не смог: "
            "значение не удалось однозначно связать с тем, о чём вы спросили.")
    if cites:
        text += f"\n\nСмотрел: {cites}"
    return text


def format_nothing_answered(filenames: list[str]) -> str:
    """Локальная модель прочитала найденное и говорит, что ответа там
    нет. Это ответ, а не сбой: владелец видит и отказ, и то, что было
    просмотрено, — и может открыть эти документы сам."""
    cites = _cite_list(filenames)
    text = "Ответа на этот вопрос в ваших документах я не нашёл."
    if cites:
        text += f"\n\nСмотрел: {cites}"
    return text
