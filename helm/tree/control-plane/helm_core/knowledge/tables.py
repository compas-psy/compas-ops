"""Восстановление строк таблицы, разорванных извлечением из PDF.

ЗАЧЕМ ЗДЕСЬ, А НЕ В ПРОВЕРКЕ ОТВЕТА. Разбор владельца 07.09.2026:
«Проверка на выходе не восстановит отношения, потерянные при извлечении
PDF». Это верно буквально. `synthesis.unbound_claims()` умеет НЕ
подтвердить значение, стоящее при чужом названии, — и не умеет связать
значение с его собственным названием, если извлечение их разорвало.
Пока разрыв не починен, честный ответ на «какой у меня холестерин» это
отказ, а не значение.

ЧТО РАЗРЫВАЕТСЯ. Лабораторный бланк — таблица; извлекатель разворачивает
её в поток строк по колонкам:

    Холестерин общий
    6.2
    ммоль/л
    3.0-5.2

Название, значение, единица и референсный диапазон оказываются четырьмя
отдельными строками. Дальше чанкинг может разрезать между ними, и тогда
отношение теряется уже необратимо: в чанке остаётся число без имени.

ВТОРАЯ ФОРМА, ИЗМЕРЕННАЯ ПРОГОНОМ 491. Тот же бланк другой вёрстки
разворачивается с пустой строкой между колонками, с колонкой отклонения
и с текстовой колонкой нормы, причём порядок колонок не тот:

    Холестерин общий
    см. комментарий

    ммоль/л

    8.4

    ↑

Прежние правила обрывались на первой же строке: «см. комментарий» не
ячейка, пустая строка — конец. Из-за этого 8.4 оставалось числом без
имени, и живой ответ владельцу 09.09.2026 был отклонён проверкой как
«значение при чужом объекте» — при том что значение было ЕГО СОБСТВЕННОЕ
и самое свежее. Отказ вместо верного ответа — та же цена, что выдумка.

ЧТО ДЕЛАЕТСЯ. Строки, которые ВМЕСТЕ составляют одну строку таблицы,
склеиваются обратно в одну текстовую строку с явными полями:

    Холестерин общий: 6.2 ммоль/л (3.0-5.2)

Склейка идёт только сверху вниз и только пока строки продолжают быть
частями значения. Ни одного нового факта здесь не появляется — меняется
только расположение уже извлечённого текста.

ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Ни модели, ни словаря показателей, ни разбора
самой PDF заново. Дата к строке не приписывается: в бланке она стоит
одна на весь раздел, и раздать её каждой строке значило бы утверждать,
что каждый показатель измерен в этот день, — чего текст не говорит.
Дата документа живёт отдельным полем источника (`content_date`).
"""

from __future__ import annotations

import re

#: Значение: число, при желании со сравнением и диапазоном. Строка,
#: состоящая ТОЛЬКО из этого, — оторванная ячейка, а не предложение.
_VALUE_ONLY_RE = re.compile(
    r"^[\s:;|—–-]*"
    r"[<>≤≥]?\s*\d+(?:[.,]\d+)?"
    r"(?:\s*[-–—]\s*\d+(?:[.,]\d+)?)?"
    r"[\s.;|]*$")

#: Единица измерения отдельной строкой: короткий токен без пробелов и
#: без кириллических слов длиннее единицы измерения.
_UNIT_ONLY_RE = re.compile(r"^[\s|]*(?P<unit>[A-Za-zА-Яа-яёЁµ%°^*/0-9]{1,12})[\s.;|]*$")
#: Форма единицы измерения. Три вида, все из живых бланков:
#: «%», «ммоль/л», «10^12/л» (степень в начале — обычная запись счётных
#: показателей крови, и без неё строка эритроцитов не склеивалась).
_UNIT_SHAPE_RE = re.compile(
    r"^(?:%"
    r"|[A-Za-zА-Яа-яёЁµ°]{1,6}(?:\^?\d+)?(?:/[A-Za-zА-Яа-яёЁµ°]{1,6})?"
    r"|\d{1,3}[\^*]\d{1,2}(?:/[A-Za-zА-Яа-яёЁµ°]{1,6})?)$")

#: Референсный диапазон отдельной строкой: два числа через тире, при
#: желании в скобках.
_RANGE_ONLY_RE = re.compile(
    r"^[\s|]*[\(\[]?\s*\d+(?:[.,]\d+)?\s*[-–—]\s*\d+(?:[.,]\d+)?\s*[\)\]]?[\s.;|]*$")

#: Название показателя: есть буквы, нет самостоятельных чисел. Цифры
#: внутри скобочной аббревиатуры («(RBC)», «Т4 свободный») названию не
#: мешают, поэтому запрещено именно число как отдельное слово.
_STANDALONE_NUMBER_RE = re.compile(r"(?<![\w.,])\d+(?:[.,]\d+)?(?![\w.,])")
_HAS_LETTERS_RE = re.compile(r"[A-Za-zА-Яа-яёЁ]{2,}")

#: Значение с единицей в одной строке — тоже ячейка: вёрстка бланка
#: бывает и такой («6.2 ммоль/л» одной строкой под названием).
_VALUE_WITH_UNIT_RE = re.compile(
    r"^[\s:;|—–-]*"
    r"(?P<value>[<>≤≥]?\s*\d+(?:[.,]\d+)?)"
    r"\s*(?P<unit>[A-Za-zА-Яа-яёЁµ%°^*/0-9]{1,12})"
    r"\s*(?:[\(\[]\s*(?P<ref>\d+(?:[.,]\d+)?\s*[-–—]\s*\d+(?:[.,]\d+)?)\s*[\)\]])?"
    r"[\s.;|]*$")

#: Колонка отклонения от нормы отдельной строкой. Только стрелки: «*»
#: и «!» сюда не берутся, их формой уже занят распознаватель единиц.
_FLAG_ONLY_RE = re.compile(r"^[\s|]*(?P<flag>[↑↓]{1,2})[\s|]*$")

#: Сколько строк-ячеек подряд может относиться к одному названию.
#: Четыре: значение, единица, диапазон и ещё одна на разнобой вёрстки.
MAX_CELL_LINES = 4

#: Длина строки, после которой это уже не ячейка таблицы, а предложение.
MAX_LABEL_CHARS = 60
#: Слов в названии показателя. Шесть — с запасом на «Холестерин
#: липопротеинов высокой плотности (ЛПВП)»; связная фраза длиннее.
MAX_LABEL_WORDS = 6


def _is_label(line: str) -> bool:
    """Название показателя: короткое, с буквами, без самостоятельных чисел.

    Ограничения длины, числа слов, запятой и конечной точки — против
    прозы: «Он сказал, что придёт в понедельник утром обязательно» с
    последующими «5» и «мм» иначе стало бы показателем со значением.
    Числа внутри скобочной аббревиатуры («(RBC)») или в имени показателя
    («Т4 свободный») названию не мешают — запрещено именно число как
    отдельное слово.
    """
    stripped = line.strip()
    return (bool(stripped)
            and len(stripped) <= MAX_LABEL_CHARS
            and len(stripped.split()) <= MAX_LABEL_WORDS
            and "," not in stripped
            and not stripped.endswith((".", "!", "?"))
            and bool(_HAS_LETTERS_RE.search(stripped))
            and not _STANDALONE_NUMBER_RE.search(stripped))


def _is_unit(line: str) -> bool:
    match = _UNIT_ONLY_RE.match(line)
    return bool(match) and bool(_UNIT_SHAPE_RE.match(match.group("unit")))


def _is_cell(cell: str) -> bool:
    """Похожа ли строка на ячейку таблицы — любую из знакомых нам."""
    if (_RANGE_ONLY_RE.match(cell) or _VALUE_ONLY_RE.match(cell)
            or _FLAG_ONLY_RE.match(cell) or _is_unit(cell)):
        return True
    combined = _VALUE_WITH_UNIT_RE.match(cell)
    return bool(combined) and bool(_UNIT_SHAPE_RE.match(combined.group("unit")))


def _label_end(lines: list[str], index: int) -> int:
    """Последняя строка названия: названия бывают перенесены.

    ПРИЗНАК ПЕРЕНОСА — НЕЗАКРЫТАЯ СКОБКА, А НЕ РЕГИСТР. «Холестерин-ЛПНП
    (липопротеины» / «низкой плотности)» — одно название в двух строках.
    Соблазнительно ловить перенос по строчной букве в начале, но тогда
    под правило попадёт и «см. комментарий» — а это ячейка колонки норм,
    и приклеить её к названию значило бы переименовать показатель.
    """
    end = index
    while (end - index < 2 and end + 1 < len(lines)
           and lines[end + 1].strip()):
        joined = " ".join(lines[index:end + 1])
        if joined.count("(") <= joined.count(")"):
            break
        end += 1
    return end


def _is_reference_note(cell: str) -> bool:
    """Текстовая норма («см. комментарий») — тоже ячейка колонки.

    Со строчной буквы: названия показателей в бланке пишутся с
    прописной, текстовые пометки — со строчной. Без этого различия
    следующая строка таблицы была бы съедена как норма предыдущей.
    """
    stripped = cell.strip()
    return bool(stripped) and stripped[:1].islower() and _is_label(stripped)


def _note_belongs_to_row(lines: list[str], cursor: int) -> bool:
    """За текстовой пометкой идёт ещё одна ячейка — значит это колонка.

    Одной пометки мало: строка «Гемоглобин» тоже короткая и без чисел.
    Ячейкой её делает то, что следом идёт значение, единица или флаг —
    в связном тексте такого продолжения не бывает.
    """
    for offset in (1, 2):
        position = cursor + offset
        if position >= len(lines):
            return False
        following = lines[position].strip()
        if following:
            return _is_cell(following)
    return False


def restore_table_rows(text: str) -> str:
    """Склеить разорванные строки таблицы. Остальной текст не трогается.

    Возвращает текст с тем же содержанием и другим расположением строк.
    """
    lines = text.split("\n")
    out: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not _is_label(line):
            out.append(line)
            index += 1
            continue

        label_end = _label_end(lines, index)
        label = " ".join(part.strip() for part in lines[index:label_end + 1])

        value = unit = reference = flag = None
        cells = 0
        consumed = label_end
        cursor = label_end + 1
        while cursor < len(lines) and cells < MAX_CELL_LINES:
            cell = lines[cursor].strip()
            if not cell:
                # ПУСТАЯ СТРОКА МЕЖДУ ЯЧЕЙКАМИ — РАЗДЕЛИТЕЛЬ КОЛОНОК.
                # Вёрстка прогона 491 ставит по пустой строке между
                # каждой парой колонок. Две пустые подряд — уже абзац,
                # там строка таблицы кончилась.
                if cursor + 1 >= len(lines) or not lines[cursor + 1].strip():
                    break
                cursor += 1
                continue
            combined = _VALUE_WITH_UNIT_RE.match(cell) if value is None else None
            if combined is not None and not _UNIT_SHAPE_RE.match(combined.group("unit")):
                # «1995» разбирается этим шаблоном как «199» и единица «5».
                # Единицей считается только то, что на единицу похоже.
                combined = None
            if reference is None and _RANGE_ONLY_RE.match(cell):
                reference = cell.strip("()[] \t.;|")
            elif combined is not None:
                value = combined.group("value").strip()
                unit = combined.group("unit")
                reference = reference or combined.group("ref")
            elif value is None and _VALUE_ONLY_RE.match(cell):
                value = cell.strip(" \t:;|.-–—")
            elif unit is None and _is_unit(cell):
                unit = _UNIT_ONLY_RE.match(cell).group("unit")
            elif flag is None and _FLAG_ONLY_RE.match(cell):
                flag = _FLAG_ONLY_RE.match(cell).group("flag")
            elif (reference is None and value is None
                  and _is_reference_note(cell)
                  and _note_belongs_to_row(lines, cursor)):
                # ТОЛЬКО ДО ЗНАЧЕНИЯ. После найденного значения короткая
                # строка с буквами — это уже название следующей строки
                # таблицы, и съесть его как норму значило бы потерять
                # целую строку бланка.
                reference = cell
            else:
                break
            cells += 1
            consumed = cursor
            cursor += 1

        # ОДНОГО ГОЛОГО ЧИСЛА НЕДОСТАТОЧНО. «Зависть» и следом «1995» —
        # это заголовок и год, а не показатель и значение. Ячейкой строка
        # признаётся, либо когда рядом есть единица измерения, либо когда
        # ячеек несколько: и то и другое бывает только в таблице.
        if value is None or (cells < 2 and not unit):
            out.append(line)
            index += 1
            continue

        restored = f"{label.rstrip(':')}: "
        restored += f"{flag} {value}" if flag else value
        if unit:
            restored += f" {unit}"
        if reference:
            restored += f" ({reference})"
        out.append(restored)
        index = consumed + 1
    return "\n".join(out)
